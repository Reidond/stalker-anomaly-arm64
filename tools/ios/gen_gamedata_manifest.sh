#!/bin/zsh
# Regenerates src/Platform/Apple/GameDataManifest.inc: the archives (and exact byte sizes) the
# shell expects in an Anomaly 1.5.3 install. Run it against a known-good copy of the game.
#
#   tools/ios/gen_gamedata_manifest.sh [path/to/Anomaly]
set -euo pipefail

repo=${0:A:h:h:h}
# game/ is gitignored, so a linked worktree has none: fall back to the main checkout's copy.
main=${$(git -C "$repo" rev-parse --path-format=absolute --git-common-dir):h}
src=${1:-$repo/game/Anomaly}
[[ -d $src/db ]] || src=$main/game/Anomaly
out=$repo/src/Platform/Apple/GameDataManifest.inc

[[ -d $src/db ]] || { echo "error: $src/db not found" >&2; exit 1; }

{
    echo "// Generated by tools/ios/gen_gamedata_manifest.sh from a clean Anomaly 1.5.3 install. Do not edit."
    echo "// {relative path, size in bytes, required}"
    cd "$src"
    find db -type f ! -name '.*' | LC_ALL=C sort | while read -r f; do
        printf '{"%s", %su, true},\n' "$f" "$(stat -f%z "$f")"
    done
    # OpenAL Soft HRTF presets used by the engine's sound code; the game runs without them.
    for f in default-*.mhr(N); do
        printf '{"%s", %su, false},\n' "$f" "$(stat -f%z "$f")"
    done
} > "$out"

echo "wrote $(grep -c '^{' "$out") entries to ${out#$repo/}"
