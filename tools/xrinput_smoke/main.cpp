// xrinput_smoke: drives xrEngine's SDL3 input and Theora decoder on macOS without the rest of the engine.
//
//   xrinput_smoke [--game-dir <dir>] [--run-dir <dir>] [--no-video]
//
// 1. CInput (the real Xr_input.cpp / xr_input_sdl.cpp), IInputReceiver and line_edit_control are fed synthetic SDL
//    events and a virtual DualSense; the test receiver must see DIK_* codes, mouse deltas, text and pad keys.
// 2. xrCore is initialized on the real game archives (as xrcore_smoke does) and CTheoraStream decodes an .ogm out of
//    them; the resolution and frame count are printed.
//
// Exit status 0 means every check passed.
#include "test_env.h"

#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <sys/stat.h>

int run_input_tests();
int run_theora_tests();

namespace
{
void engine_log(LPCSTR line) { printf("    | %s\n", line); }

bool is_dir(const std::string& native)
{
	string_path virtual_path;
	xr_virtual_path(native.c_str(), virtual_path, sizeof(virtual_path));
	struct stat st;
	return stat(xr_native_path(virtual_path), &st) == 0 && S_ISDIR(st.st_mode);
}

void make_dirs(const std::string& path)
{
	for (size_t i = 1; i <= path.size(); ++i)
		if (i == path.size() || path[i] == '/')
			mkdir(path.substr(0, i).c_str(), 0755);
}

std::string with_trailing_slash(std::string p)
{
	if (!p.empty() && p.back() != '/')
		p += '/';
	return p;
}

// fsgame.ltx for the run: the game's own file with $app_data_root$ redirected, plus an explicit $fs_root$.
bool write_fsgame(const std::string& game_dir, const std::string& run_dir, const std::string& out_path)
{
	string_path virtual_path;
	xr_virtual_path((game_dir + "fsgame.ltx").c_str(), virtual_path, sizeof(virtual_path));
	std::ifstream in(xr_native_path(virtual_path));
	if (!in)
	{
		printf("cannot read %sfsgame.ltx\n", game_dir.c_str());
		return false;
	}
	std::ofstream out(out_path, std::ios::trunc);
	out << "; generated by xrinput_smoke; the game directory is only ever read\n";
	out << "$fs_root$ = false | false | " << game_dir << "\n";
	std::string line;
	while (std::getline(in, line))
	{
		if (!line.empty() && line.back() == '\r')
			line.pop_back();
		if (line.rfind("$app_data_root$", 0) == 0)
			line = "$app_data_root$ = true | false | " + run_dir + "appdata/";
		out << line << "\n";
	}
	return out.good();
}
} // namespace

int main(int argc, char** argv)
{
	setvbuf(stdout, nullptr, _IOLBF, 0);
	std::string game_dir = XRINPUT_SMOKE_DEFAULT_GAME_DIR;
	std::string run_dir = XRINPUT_SMOKE_RUN_DIR;
	bool video = true;
	if (const char* env = getenv("ANOMALY_GAME_DIR"))
		game_dir = env;
	for (int i = 1; i < argc; ++i)
	{
		if (!strcmp(argv[i], "--game-dir") && i + 1 < argc) game_dir = argv[++i];
		else if (!strcmp(argv[i], "--run-dir") && i + 1 < argc) run_dir = argv[++i];
		else if (!strcmp(argv[i], "--no-video")) video = false;
	}
	game_dir = with_trailing_slash(game_dir);
	run_dir = with_trailing_slash(run_dir);

	printf("xrinput_smoke\n  game dir: %s\n  run dir : %s\n", game_dir.c_str(), run_dir.c_str());
	make_dirs(run_dir + "appdata");

	// xrCore up first: CInput logs through it and the Theora test reads the archives with it
	Debug._initialize(false);
	std::string fsgame;
	if (video && is_dir(game_dir + "db"))
	{
		fsgame = run_dir + "fsgame.ltx";
		if (!write_fsgame(game_dir, run_dir, fsgame))
			return 2;
		Core._initialize("xrinput_smoke", engine_log, TRUE, fsgame.c_str());
	}
	else
	{
		if (video)
			printf("no db/ in the game directory; skipping the video test (pass --game-dir or set ANOMALY_GAME_DIR)\n");
		video = false;
		Core._initialize("xrinput_smoke", engine_log, FALSE, nullptr);
	}

	int failures = run_input_tests();
	if (video)
		failures = run_theora_tests();

	printf("\nxrinput_smoke: %s (%d failed)\n", failures ? "FAILED" : "all checks passed", failures);
	return failures ? 1 : 0;
}
