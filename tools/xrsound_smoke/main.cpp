// xrsound_smoke: checks that xrSound plays sound on Apple platforms against the real Anomaly game data.
//
//   xrsound_smoke [--game-dir <dir>] [--run-dir <dir>] [--sound <name>] [--seconds <n>]
//                 [--list [prefix]] [--dump-ogg <file>] [--device <name>]
//
// What it does:
//   1. Initializes xrCore against the (read-only) game directory, as tools/xrcore_smoke does: archives mounted,
//      logs and caches in the run directory.
//   2. Creates the sound manager the way xrEngine does (stage 0: device list, stage 1: device, context, EFX, targets).
//   3. Loads an .ogg out of the archives through the engine's own path (ref_sound::create) and decodes it once more,
//      on its own, to time the Ogg Vorbis decoder.
//   4. Plays it 2D, then 3D on a source that moves from left to right, about --seconds (default 2) each, running the
//      engine's Sound->update() at 60 Hz, and samples the OpenAL source state on the way.
//   5. Reports the device, the EFX/HRTF state and the timings.
//
// --list prints the .ogg names under $game_sounds$; --dump-ogg writes the raw Ogg bytes of the chosen sound to a file
// (the iOS build bundles such a file as its only sound, because the game archives are not on the device).
// Exit status 0 means every check passed.
