using clk = std::chrono::steady_clock;
int g_failures = 0;

void check(bool ok, const char* what)
{
	printf("  [%s] %s\n", ok ? " ok " : "FAIL", what);
	if (!ok)
		++g_failures;
}

void engine_log(LPCSTR line) { printf("    | %s\n", line); }

double ms_since(clk::time_point t0) { return std::chrono::duration<double, std::milli>(clk::now() - t0).count(); }

void make_dirs(const std::string& path)
{
	for (size_t i = 1; i <= path.size(); ++i)
		if (i == path.size() || path[i] == '/')
			mkdir(path.substr(0, i).c_str(), 0755);
}

std::string with_trailing_slash(std::string p)
{
	if (!p.empty() && p.back() != '/')
		p += '/';
	return p;
}

bool is_dir(const std::string& native)
{
	string_path virtual_path;
	xr_virtual_path(native.c_str(), virtual_path, sizeof(virtual_path));
	struct stat st;
	return stat(xr_native_path(virtual_path), &st) == 0 && S_ISDIR(st.st_mode);
}

// fsgame.ltx for the run: the game's own file with $app_data_root$ redirected, plus an explicit $fs_root$.
bool write_fsgame(const std::string& game_dir, const std::string& run_dir, const std::string& out_path)
{
	string_path virtual_path;
	xr_virtual_path((game_dir + "fsgame.ltx").c_str(), virtual_path, sizeof(virtual_path));
	std::ifstream in(xr_native_path(virtual_path));
	if (!in)
	{
		printf("cannot read %sfsgame.ltx\n", game_dir.c_str());
		return false;
	}
	std::ofstream out(out_path, std::ios::trunc);
	out << "; generated by xrsound_smoke; the game directory is only ever read\n";
	out << "$fs_root$ = false | false | " << game_dir << "\n";
	std::string line;
	while (std::getline(in, line))
	{
		if (!line.empty() && line.back() == '\r')
			line.pop_back();
		if (line.rfind("$app_data_root$", 0) == 0)
			line = "$app_data_root$ = true | false | " + run_dir + "appdata/";
		out << line << "\n";
	}
	return out.good();
}

// ---- OpenAL probing -------------------------------------------------------------------------------------------

struct PlayingSource
{
	ALuint id = 0;
	ALfloat pos[3] = {};
	ALint relative = 0;
	ALfloat offset = 0.f;
	ALint processed = 0, queued = 0;
	int count = 0; // sources in AL_PLAYING
};

// The engine pre-creates psSoundTargets sources; the one(s) in AL_PLAYING are the emitters being rendered.
PlayingSource probe_playing()
{
	PlayingSource r;
	for (ALuint id = 1; id <= 4096; ++id)
	{
		if (!alIsSource(id))
			continue;
		ALint state = 0;
		alGetSourcei(id, AL_SOURCE_STATE, &state);
		if (state != AL_PLAYING)
			continue;
		if (++r.count == 1)
		{
			r.id = id;
			alGetSourcefv(id, AL_POSITION, r.pos);
			alGetSourcei(id, AL_SOURCE_RELATIVE, &r.relative);
			alGetSourcef(id, AL_SEC_OFFSET, &r.offset);
			alGetSourcei(id, AL_BUFFERS_PROCESSED, &r.processed);
			alGetSourcei(id, AL_BUFFERS_QUEUED, &r.queued);
		}
	}
	return r;
}

void report_device()
{
	ALCcontext* ctx = alcGetCurrentContext();
	ALCdevice* dev = ctx ? alcGetContextsDevice(ctx) : nullptr;
	check(dev != nullptr, "OpenAL context is current");
	if (!dev)
		return;
	const char* name = alcIsExtensionPresent(dev, "ALC_ENUMERATE_ALL_EXT") ? alcGetString(dev, ALC_ALL_DEVICES_SPECIFIER)
	                                                                      : nullptr;
	if (!name || !*name)
		name = alcGetString(dev, ALC_DEVICE_SPECIFIER);
	ALCint freq = 0, sends = 0, mono = 0, stereo = 0, efx_major = 0, efx_minor = 0, hrtf = -1, hrtf_count = 0;
	alcGetIntegerv(dev, ALC_FREQUENCY, 1, &freq);
	alcGetIntegerv(dev, ALC_MONO_SOURCES, 1, &mono);
	alcGetIntegerv(dev, ALC_STEREO_SOURCES, 1, &stereo);
	printf("  device          : %s\n", name ? name : "?");
	printf("  AL renderer     : %s / %s\n", alGetString(AL_VENDOR), alGetString(AL_RENDERER));
	printf("  AL version      : %s\n", alGetString(AL_VERSION));
	printf("  output          : %d Hz, %d mono + %d stereo sources\n", freq, mono, stereo);
	const bool efx = alcIsExtensionPresent(dev, "ALC_EXT_EFX") == ALC_TRUE;
	if (efx)
	{
		alcGetIntegerv(dev, ALC_EFX_MAJOR_VERSION, 1, &efx_major);
		alcGetIntegerv(dev, ALC_EFX_MINOR_VERSION, 1, &efx_minor);
		alcGetIntegerv(dev, ALC_MAX_AUXILIARY_SENDS, 1, &sends);
	}
	printf("  EFX             : %s", efx ? "available" : "NOT available");
	if (efx)
		printf(" (v%d.%d, %d aux sends)", efx_major, efx_minor, sends);
	printf("\n");
	// the engine's own use of EFX: one EAX-reverb effect in one auxiliary slot, created in CSoundRender_CoreA::LoadEffect
	bool slot_found = false;
	auto is_slot = (LPALISAUXILIARYEFFECTSLOT)alGetProcAddress("alIsAuxiliaryEffectSlot");
	if (is_slot)
		for (ALuint s = 1; s <= 16 && !slot_found; ++s)
			slot_found = is_slot(s) == AL_TRUE;
	printf("  engine EFX slot : %s\n", slot_found ? "created (EAX reverb)" : "none");
	if (alcIsExtensionPresent(dev, "ALC_SOFT_HRTF"))
	{
		alcGetIntegerv(dev, ALC_HRTF_STATUS_SOFT, 1, &hrtf);
		alcGetIntegerv(dev, ALC_NUM_HRTF_SPECIFIERS_SOFT, 1, &hrtf_count);
		static const char* const status[] = {"disabled", "enabled", "denied", "required", "headphones detected",
		                                     "unsupported format"};
		printf("  HRTF            : %s", hrtf >= 0 && hrtf < 6 ? status[hrtf] : "?");
		auto get_str = (LPALCGETSTRINGISOFT)alcGetProcAddress(dev, "alcGetStringiSOFT");
		if (hrtf == ALC_HRTF_ENABLED_SOFT || hrtf == ALC_HRTF_HEADPHONES_DETECTED_SOFT)
			printf(" (%s)", alcGetString(dev, ALC_HRTF_SPECIFIER_SOFT));
		printf(", %d data set(s)", hrtf_count);
		if (get_str)
			for (ALCint i = 0; i < hrtf_count; ++i)
				printf("%s'%s'", i ? ", " : ": ", get_str(dev, ALC_HRTF_SPECIFIER_SOFT, i));
		printf("\n");
	}
	check(efx, "EFX available");
	check(slot_found, "engine created its EFX auxiliary slot");
}

// ---- Ogg decode timing ------------------------------------------------------------------------------------------

struct MemFile
{
	const u8* data;
	size_t size, pos;
};

size_t mem_read(void* ptr, size_t size, size_t n, void* src)
{
	MemFile* f = static_cast<MemFile*>(src);
	size_t count = std::min(n, size ? (f->size - f->pos) / size : 0);
	memcpy(ptr, f->data + f->pos, count * size);
	f->pos += count * size;
	return count;
}
int mem_seek(void* src, ogg_int64_t off, int whence)
{
	MemFile* f = static_cast<MemFile*>(src);
	ogg_int64_t base = whence == SEEK_SET ? 0 : whence == SEEK_CUR ? (ogg_int64_t)f->pos : (ogg_int64_t)f->size;
	ogg_int64_t p = base + off;
	if (p < 0 || p > (ogg_int64_t)f->size)
		return -1;
	f->pos = (size_t)p;
	return 0;
}
int mem_close(void*) { return 0; }
long mem_tell(void* src) { return (long)static_cast<MemFile*>(src)->pos; }

struct DecodeResult
{
	bool ok = false;
	double ms = 0;
	long channels = 0, rate = 0;
	double seconds = 0;
	size_t pcm_bytes = 0;
};

DecodeResult decode_whole(const u8* data, size_t size)
{
	DecodeResult r;
	OggVorbis_File vf;
	MemFile mf{data, size, 0};
	ov_callbacks cb = {mem_read, mem_seek, mem_close, mem_tell};
	auto t0 = clk::now();
	if (ov_open_callbacks(&mf, &vf, nullptr, 0, cb) != 0)
		return r;
	vorbis_info* vi = ov_info(&vf, -1);
	r.channels = vi->channels;
	r.rate = vi->rate;
	std::vector<char> buf(64 * 1024);
	int section = 0;
	for (;;)
	{
		long n = ov_read(&vf, buf.data(), (int)buf.size(), 0, 2, 1, &section);
		if (n <= 0)
			break;
		r.pcm_bytes += (size_t)n;
	}
	r.ms = ms_since(t0);
	r.seconds = r.pcm_bytes / double(2 * std::max<long>(r.channels, 1) * std::max<long>(r.rate, 1));
	ov_clear(&vf);
	r.ok = r.pcm_bytes > 0;
	return r;
}

// ---- sound selection ----------------------------------------------------------------------------------------------

std::string normalize(std::string name)
{
	for (char& c : name)
		c = (char)tolower((unsigned char)c);
	if (name.size() > 4 && name.compare(name.size() - 4, 4, ".ogg") == 0)
		name.resize(name.size() - 4);
	return name;
}

// A mono 44.1 kHz effect a second or more long, so that it can be placed in 3D and heard for the whole phase.
// Weapon and ambient sounds are tried first; the list is walked in registry order otherwise.
std::string pick_sound(const FS_FileSet& files, ref_sound& out)
{
	auto usable = [&](const std::string& n)
	{
		ref_sound s;
		s.create(n.c_str(), st_Effect, sg_SourceType);
		CSound_source* h = s._handle();
		bool ok = h && h->channels_num() == 1 && h->length_sec() >= 1.0f && h->length_sec() <= 12.0f;
		if (ok)
			out = s;
		s.destroy();
		return ok;
	};
	static const char* const preferred[] = {"weapons\\", "ambient\\", "anomaly\\", "monsters\\"};
	int tried = 0;
	for (const char* prefix : preferred)
		for (const FS_File& f : files)
		{
			std::string n = normalize(f.name.c_str());
			if (n.rfind(prefix, 0) != 0 || ++tried > 400)
				continue;
			if (usable(n))
				return n;
		}
	return std::string();
}
