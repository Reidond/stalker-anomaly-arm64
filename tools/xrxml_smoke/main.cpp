// xrxml_smoke: headless check of xrXMLParser (CXml, TinyXML) on Apple platforms against the real game data.
//
//   xrxml_smoke [--game-dir <dir>] [--run-dir <dir>]
//
// What it does:
//   1. Initializes xrCore against the (read-only) game directory, like tools/xrcore_smoke: a generated fsgame.ltx in the
//      run directory keeps logs and caches out of the game data.
//   2. Parses a document from memory (LoadFromString): navigation, text, attributes, node counts, numeric entities.
//   3. Parses every XML file found under $game_config$ (text tables, UI layouts, ...) out of the archives through CXml::Load,
//      with its #include handling, and reads a few values from them.
//
// Exit status 0 means every check passed, 77 means there was no game data to test against.
#include "xrCore/xrCore.h"
#include "xrXMLParser/xrXMLParser.h"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <string>
#include <sys/stat.h>

// xrGame's hook that runs a script callback on every loaded document (ScriptXMLInit.cpp); nothing to do here
void XMLLuaCallback(CXml&, LPCSTR) {}

namespace
{
int g_failures = 0;
int g_checks = 0;

void check(bool ok, const char* what)
{
	++g_checks;
	if (!ok)
		++g_failures;
	printf("  [%s] %s\n", ok ? " ok " : "FAIL", what);
}

void engine_log(LPCSTR) {}

void make_dirs(const std::string& path)
{
	for (size_t i = 1; i <= path.size(); ++i)
		if (i == path.size() || path[i] == '/')
			mkdir(path.substr(0, i).c_str(), 0755);
}

std::string with_trailing_slash(std::string p)
{
	if (!p.empty() && p.back() != '/')
		p += '/';
	return p;
}

bool write_fsgame(const std::string& game_dir, const std::string& run_dir, const std::string& out_path)
{
	string_path virtual_path;
	xr_virtual_path((game_dir + "fsgame.ltx").c_str(), virtual_path, sizeof(virtual_path));
	std::ifstream in(xr_native_path(virtual_path));
	if (!in)
		return false;
	std::ofstream out(out_path, std::ios::trunc);
	out << "; generated by xrxml_smoke; the game directory is only ever read\n";
	out << "$fs_root$ = false | false | " << game_dir << "\n";
	std::string line;
	while (std::getline(in, line))
	{
		if (!line.empty() && line.back() == '\r')
			line.pop_back();
		if (line.rfind("$app_data_root$", 0) == 0)
			line = "$app_data_root$ = true | false | " + run_dir + "appdata/";
		out << line << "\n";
	}
	return out.good();
}

void test_from_string()
{
	printf("\n[1] a document from memory\n");
	static const char* xml =
		"<?xml version=\"1.0\" encoding=\"windows-1251\"?>\n"
		"<root>\n"
		"  <item id=\"a\" value=\"1.5\">first</item>\n"
		"  <item id=\"b\" value=\"-7\">second &amp; third</item>\n"
		"  <item id=\"c\" value=\"4294967295\"/>\n"
		"  <group><leaf n=\"3\">42</leaf><leaf n=\"4\">0.25</leaf></group>\n"
		"  <esc>&#65;&#x42;&#x20AC;</esc>\n"
		"</root>\n";
	CXml doc;
	doc.LoadFromString(xml);
	check(doc.GetRoot() != nullptr, "parsed, root element present");
	check(doc.GetNodesNum(doc.GetRoot(), "item") == 3, "GetNodesNum counts 3 items");
	check(!strcmp(doc.Read("item", 0, ""), "first"), "Read item[0] (paths are relative to the root element)");
	check(!strcmp(doc.Read("item", 1, ""), "second & third"), "entities in text are decoded");
	check(!strcmp(doc.ReadAttrib("item", 1, "id"), "b"), "ReadAttrib");
	check(doc.ReadAttribFlt("item", 0, "value", 0.f) == 1.5f, "ReadAttribFlt");
	check(doc.ReadAttribInt("item", 1, "value", 0) == -7, "ReadAttribInt (negative)");
	check(doc.ReadInt("group:leaf", 0, 0) == 42, "ReadInt on a nested node");
	check(doc.ReadFlt(doc.NavigateToNode("group"), "leaf", 1, 0.f) == 0.25f, "ReadFlt, second node of the same name");
	check(doc.NavigateToNode("group:missing") == nullptr, "a missing path gives null");
	check(!strcmp(doc.Read("group:missing", 0, "dflt"), "dflt"), "the default value is returned for a missing node");
	XML_NODE* found = doc.SearchForAttribute(doc.GetRoot()->FirstChild("item"), "item", "id", "c");
	check(found != nullptr, "SearchForAttribute finds item c");
	const char* esc = doc.Read("esc", 0, "");
	check(esc[0] == 'A' && esc[1] == 'B', "numeric character references (decimal and hex) are decoded");
	// 0xFFFFFFFF does not fit a 32-bit int in sscanf("%d"): the attribute still reads without crashing
	(void)doc.ReadAttribInt("item", 2, "value", 0);
}

void test_game_files()
{
	printf("\n[2] XML files from the game archives\n");
	xr_vector<LPSTR>* list = FS.file_list_open("$game_config$", FS_ListFiles);
	check(list != nullptr && !list->empty(), "$game_config$ lists files");
	if (!list)
		return;
	int parsed = 0, failed_probe = 0, with_root = 0, empty = 0, malformed = 0;
	long nodes = 0;
	std::string first_name, table_name;
	for (LPSTR name : *list)
	{
		const char* ext = strext(name);
		if (!ext || strcmp(ext, ".xml") != 0)
			continue;
		// CXml::Load takes the directory and the file name apart; files directly under $game_config$ have no directory
		const char* slash = strrchr(name, '\\');
		if (!slash)
			continue;
		string_path dir;
		xr_strcpy(dir, sizeof(dir), name);
		dir[slash - name] = 0;
		// CXml::Load asserts when a document does not parse, as it would in the game. A few shipped files are empty
		// placeholders or have a typo, so well-formedness is checked first (files with #include lines are not XML
		// until CXml has expanded them, those go straight to CXml)
		IReader* raw = FS.r_open("$game_config$", name);
		std::string text;
		if (raw)
		{
			text.assign((const char*)raw->pointer(), raw->length());
			FS.r_close(raw);
		}
		if (text.find('<') == std::string::npos)
		{
			++empty;
			continue;
		}
		if (text.find("#include") == std::string::npos)
		{
			TiXmlDocument probe;
			probe.Parse(&probe, text.c_str());
			if (probe.Error())
			{
				printf("    not well-formed in the shipped data: %s (%s)\n", name, probe.ErrorDesc());
				++malformed;
				continue;
			}
		}
		// ui layouts that #include siblings are handled by CXml::Load
		CXml doc;
		doc.Load("$game_config$", dir, slash + 1);
		++parsed;
		if (doc.GetRoot())
		{
			++with_root;
			nodes += doc.GetNodesNum(doc.GetRoot(), "string") + doc.GetNodesNum(doc.GetRoot(), "text");
		}
		else
		{
			printf("    no root element (comments only?): %s\n", name);
			++failed_probe;
		}
		if (strstr(name, "text\\eng\\") == name && table_name.empty() && doc.GetRoot() &&
			doc.GetNodesNum(doc.GetRoot(), "string") > 10)
			table_name = slash + 1;
		if (first_name.empty())
			first_name = name;
	}
	FS.file_list_close(list);
	char what[200];
	snprintf(what, sizeof(what), "%d XML files under $game_config$ parsed (first: %s)", parsed, first_name.c_str());
	check(parsed > 20, what);
	snprintf(what, sizeof(what), "all but a few parsed files have a root element (%d without)", failed_probe);
	check(failed_probe < 10, what);
	printf("  <string>/<text> nodes seen: %ld; skipped: %d empty, %d malformed (upstream data)\n", nodes, empty, malformed);
	check(malformed < 10, "only a handful of shipped files are not well-formed");

	// a string table: root <string_table> with <string id="..."><text>...</text></string>
	if (!table_name.empty())
	{
		CXml table;
		table.Load("$game_config$", "text\\eng", table_name.c_str());
		const int strings = table.GetNodesNum(table.GetRoot(), "string");
		snprintf(what, sizeof(what), "text\\eng\\%s: %d <string> entries", table_name.c_str(), strings);
		check(strings > 10, what);
		const char* id = table.ReadAttrib(table.GetRoot(), "string", 0, "id", "");
		XML_NODE* first = table.NavigateToNode(table.GetRoot(), "string", 0);
		snprintf(what, sizeof(what), "... the first entry has an id (%s) and a text", id);
		check(id[0] != 0 && first != nullptr && table.Read(first, "text", 0, "")[0] != 0, what);
	}
	else
		printf("  (no string table under text\\eng found; skipped)\n");
}
} // namespace

int main(int argc, char** argv)
{
	setvbuf(stdout, nullptr, _IOLBF, 0);
	std::string game_dir = XRXML_SMOKE_DEFAULT_GAME_DIR;
	std::string run_dir = XRXML_SMOKE_RUN_DIR;
	if (const char* env = getenv("ANOMALY_GAME_DIR"))
		game_dir = env;
	for (int i = 1; i + 1 < argc; ++i)
	{
		if (!strcmp(argv[i], "--game-dir")) game_dir = argv[++i];
		else if (!strcmp(argv[i], "--run-dir")) run_dir = argv[++i];
	}
	game_dir = with_trailing_slash(game_dir);
	run_dir = with_trailing_slash(run_dir);
	printf("xrxml_smoke\n  game dir: %s\n  run dir : %s\n", game_dir.c_str(), run_dir.c_str());

	Debug._initialize(false);
	// the in-memory part needs no game data
	Core._initialize("xrxml_smoke", engine_log, FALSE);
	test_from_string();
	Core._destroy();

	struct stat st;
	if (stat((game_dir + "fsgame.ltx").c_str(), &st) != 0)
	{
		printf("\nno game data (fsgame.ltx) in the game directory; the archive part is skipped\n");
		return g_failures ? 1 : 77;
	}
	make_dirs(run_dir + "appdata");
	const std::string fsgame = run_dir + "fsgame.ltx";
	if (!write_fsgame(game_dir, run_dir, fsgame))
		return 2;
	Core._initialize("xrxml_smoke", engine_log, TRUE, fsgame.c_str());
	test_game_files();
	printf("\n%d checks, %d failed\n", g_checks, g_failures);
	Core._destroy();
	return g_failures ? 1 : 0;
}
