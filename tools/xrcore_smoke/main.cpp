// xrcore_smoke: headless check that xrCore works on Apple platforms against the real Anomaly game data.
//
//   xrcore_smoke [--game-dir <dir>] [--run-dir <dir>] [--crash-test segv|assert|abort]
//   xrcore_smoke --log-race [seconds]      threads that log, flush and read the log while the core shuts down (for ThreadSanitizer)
//
// --crash-test skips the checks and, right after initialization, triggers a fault to exercise the crash reporting:
// the process must print a stack trace, leave a report next to the log and die with the original signal (or exit 1 for
// assert).
//
// What it does:
//   1. Writes a fsgame.ltx into the run directory that points $fs_root$ at the (read-only) game directory and
//      $app_data_root$ at <run>/appdata, so logs, saves and caches never touch the game data.
//   2. Initializes xrCore with it, which scans the game directory and mounts every .db* archive.
//   3. Prints registry / archive statistics and the first lines of configs/system.ltx read out of an archive.
//   4. Reads a texture through both archive read paths (whole-entry reader and windowed stream reader) and compares.
//   5. Exercises the mixed-case path handling, timers, locks and parallel helpers.
//
// Exit status 0 means every check passed.
#include "xrCore/xrCore.h"
#include "xrCore/stream_reader.h"

#include <atomic>
#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <string>
#include <sys/stat.h>
#include <thread>
#include <vector>

#ifndef XRCORE_SMOKE_OLD_LOG_API
# include "xrCore/log_lines.h"
#endif

namespace
{
int g_failures = 0;

void check(bool ok, const char* what)
{
	printf("  [%s] %s\n", ok ? " ok " : "FAIL", what);
	if (!ok)
		++g_failures;
}

void engine_log(LPCSTR line) { printf("    | %s\n", line); }

bool is_dir(const std::string& native)
{
	// resolved through the path layer: "db" may be spelled "DB" on disk
	string_path virtual_path;
	xr_virtual_path(native.c_str(), virtual_path, sizeof(virtual_path));
	struct stat st;
	return stat(xr_native_path(virtual_path), &st) == 0 && S_ISDIR(st.st_mode);
}

void make_dirs(const std::string& path)
{
	for (size_t i = 1; i <= path.size(); ++i)
		if (i == path.size() || path[i] == '/')
			mkdir(path.substr(0, i).c_str(), 0755);
}

std::string with_trailing_slash(std::string p)
{
	if (!p.empty() && p.back() != '/')
		p += '/';
	return p;
}

// fsgame.ltx for the run: the game's own file with $app_data_root$ redirected, plus an explicit $fs_root$.
bool write_fsgame(const std::string& game_dir, const std::string& run_dir, const std::string& out_path)
{
	// through the path layer, so a differently-cased fsgame.ltx is found on a case-sensitive volume
	string_path virtual_path;
	xr_virtual_path((game_dir + "fsgame.ltx").c_str(), virtual_path, sizeof(virtual_path));
	std::ifstream in(xr_native_path(virtual_path));
	if (!in)
	{
		printf("cannot read %sfsgame.ltx\n", game_dir.c_str());
		return false;
	}
	std::ofstream out(out_path, std::ios::trunc);
	out << "; generated by xrcore_smoke; the game directory is only ever read\n";
	out << "$fs_root$ = false | false | " << game_dir << "\n";
	std::string line;
	while (std::getline(in, line))
	{
		if (!line.empty() && line.back() == '\r')
			line.pop_back();
		if (line.rfind("$app_data_root$", 0) == 0)
			line = "$app_data_root$ = true | false | " + run_dir + "appdata/";
		out << line << "\n";
	}
	return out.good();
}

struct SharedCounter
{
	xrCriticalSection lock;
	int value = 0;
};

void counter_thread(void* arg)
{
	SharedCounter* c = static_cast<SharedCounter*>(arg);
	for (int i = 0; i < 10000; ++i)
	{
		xrCriticalSectionGuard guard(c->lock);
		++c->value;
	}
	// signalled through the (separately locked) value below
	xrCriticalSectionGuard guard(c->lock);
	c->value += 1000000;
}

// FNV-1a, chainable across buffers (xrCore's own crc32 is not).
u64 fnv1a(const void* data, size_t size, u64 hash = 1469598103934665603ull)
{
	const u8* p = static_cast<const u8*>(data);
	for (size_t i = 0; i < size; ++i)
		hash = (hash ^ p[i]) * 1099511628211ull;
	return hash;
}

u64 hash_of_reader(IReader* r)
{
	return fnv1a(r->pointer(), (size_t)r->length());
}

u64 hash_of_stream(CStreamReader* r)
{
	u64 hash = 1469598103934665603ull;
	u8 buffer[64 * 1024];
	while (r->elapsed())
	{
		u32 n = _min(r->elapsed(), (u32)sizeof(buffer));
		r->r(buffer, n);
		hash = fnv1a(buffer, n, hash);
	}
	return hash;
}
// --log-race: what the engine does to the log while it runs and shuts down, with the threads it has: several that log (the
// ALife/secondary thread, sound, workers), the freeze watchdog that flushes the log when the main thread is busy (it lives until the
// process ends, also while Core._destroy() closes the log and frees the file system), the console that draws the last lines, and
// clear_log. Run it under ThreadSanitizer (cmake --preset macos-arm64-tsan, target xrcore_smoke): a race is reported even when this
// run does not crash.
int log_race(int seconds)
{
	std::atomic<bool> stop_loggers{false}, stop_freeze{false};
	std::vector<std::thread> threads;
	for (int id = 0; id < 3; ++id)
		threads.emplace_back([&, id] {
			for (int i = 0; !stop_loggers.load(); ++i)
			{
				Msg("log-race logger %d line %d", id, i % 40);
				if (i % 7 == 0)
					Msg("log-race repeated line"); // the dedupe path: the last line is rewritten with a counter
				if (i % 64 == 0)
					std::this_thread::sleep_for(std::chrono::microseconds(200));
			}
		});
	std::thread freeze([&] {
		while (!stop_freeze.load())
		{
			FlushLog(); // mt_FreezeThread
			std::this_thread::sleep_for(std::chrono::milliseconds(1));
		}
	});
	threads.emplace_back([&] {
		string1024 sink;
		while (!stop_loggers.load())
		{
#ifdef XRCORE_SMOKE_OLD_LOG_API
			// CConsole::OnRender before the log lock existed
			u32 last = LogFile.size() - 1;
			for (int i = last; i >= 0 && i + 40 > (int)last; --i)
				xr_strcpy(sink, LogFile[i].c_str());
#else
			xr_vector<xr_string> lines;
			const u32 first = LogCopyLines(LogLineCount() - 1, 40, lines);
			for (size_t i = 0; i < lines.size(); ++i)
				xr_strcpy(sink, lines[i].c_str());
			(void)first;
#endif
			std::this_thread::sleep_for(std::chrono::microseconds(300));
		}
	});
	threads.emplace_back([&] {
		while (!stop_loggers.load())
		{
			std::this_thread::sleep_for(std::chrono::milliseconds(50));
#ifdef XRCORE_SMOKE_OLD_LOG_API
			LogFile.clear_not_free(); // the clear_log console command
#else
			ClearLog();
#endif
		}
	});

	std::this_thread::sleep_for(std::chrono::seconds(seconds));
	// the engine's shutdown: the game and the renderer are gone and log their last lines; then Core._destroy() closes the log and
	// deletes the file system while the freeze watchdog is still running
	stop_loggers.store(true);
	for (std::thread& t : threads)
		t.join();
	Core._destroy();
	std::this_thread::sleep_for(std::chrono::milliseconds(50)); // the watchdog flushes into a file system that is gone
	stop_freeze.store(true);
	freeze.join();
	printf("log-race: finished\n");
	return 0;
}
} // namespace

int main(int argc, char** argv)
{
	setvbuf(stdout, nullptr, _IOLBF, 0); // keep output ordered if an assert ends the process
	std::string game_dir = XRCORE_SMOKE_DEFAULT_GAME_DIR;
	std::string run_dir = XRCORE_SMOKE_RUN_DIR;
	std::string crash_test;
	int log_race_seconds = 0;
	for (int i = 1; i < argc; ++i)
		if (!strcmp(argv[i], "--log-race"))
			log_race_seconds = (i + 1 < argc && atoi(argv[i + 1]) > 0) ? atoi(argv[i + 1]) : 3;
	if (const char* env = getenv("ANOMALY_GAME_DIR"))
		game_dir = env;
	for (int i = 1; i + 1 < argc; ++i)
	{
		if (!strcmp(argv[i], "--game-dir")) game_dir = argv[++i];
		else if (!strcmp(argv[i], "--run-dir")) run_dir = argv[++i];
		else if (!strcmp(argv[i], "--crash-test")) crash_test = argv[++i];
	}
	game_dir = with_trailing_slash(game_dir);
	run_dir = with_trailing_slash(run_dir);

	printf("xrcore_smoke\n  game dir: %s\n  run dir : %s\n", game_dir.c_str(), run_dir.c_str());
	if (!is_dir(game_dir + "db"))
	{
		printf("no db/ in the game directory; pass --game-dir or set ANOMALY_GAME_DIR\n");
		return 2;
	}
	make_dirs(run_dir + "appdata");
	const std::string fsgame = run_dir + "fsgame.ltx";
	if (!write_fsgame(game_dir, run_dir, fsgame))
		return 2;

	// ---------------------------------------------------------------------------------------------
	printf("\n[1] initialize xrCore (scan + mount archives)\n");
	// Like the engine's entry point: crash handlers first, then the core.
	Debug._initialize(false);
	// Params are taken from the command line; the generated fsgame.ltx is passed explicitly instead.
	Core._initialize("xrcore_smoke", engine_log, TRUE, fsgame.c_str());
	if (log_race_seconds)
		return log_race(log_race_seconds);
	if (!crash_test.empty())
	{
		printf("triggering '%s'\n", crash_test.c_str());
		if (crash_test == "assert") { R_ASSERT2(false, "deliberate assertion from xrcore_smoke"); }
		else if (crash_test == "abort") abort();
		else { volatile int* p = nullptr; *p = 1; }
		return 3; // not reached
	}
	check(FS.m_Flags.is(CLocatorAPI::flReady), "file system ready");
	check(xr_FS != nullptr && FS.path_exist("$app_data_root$"), "app data root registered");
	string_path appdata;
	FS.update_path(appdata, "$app_data_root$", "");
	{
		// registry paths are lower case and '\\' separated
		string_path expected;
		xr_virtual_path(run_dir.c_str(), expected, sizeof(expected));
		check(strncasecmp(appdata, expected, strlen(expected)) == 0, "app data root is inside the run directory");
	}

	// ---------------------------------------------------------------------------------------------
	printf("\n[2] archives\n");
	CLocatorAPI::registry_stats stats;
	FS.get_stats(stats);
	printf("  archives mounted : %zu\n", FS.m_archives.size());
	printf("  registry entries : %zu (%zu archived files, %zu loose files, %zu folders)\n", stats.entries,
	       stats.archived_files, stats.loose_files, stats.folders);
	for (size_t i = 0; i < FS.m_archives.size() && i < 8; ++i)
	{
		string_path name;
		xr_virtual_path(*FS.m_archives[i].path, name, sizeof(name));
		const char* base = strrchr(name, '\\');
		printf("    #%-2zu %-28s %8u files  %9u bytes\n", i, base ? base + 1 : name, stats.per_archive[i],
		       FS.m_archives[i].size);
	}
	if (FS.m_archives.size() > 8)
		printf("    ... %zu more\n", FS.m_archives.size() - 8);
	check(!FS.m_archives.empty(), "at least one archive mounted");
	check(stats.archived_files > 1000, "archives contribute files");

	// ---------------------------------------------------------------------------------------------
	printf("\n[3] configs\\system.ltx from an archive\n");
	const CLocatorAPI::file* cfg = FS.exist("$game_config$", "system.ltx");
	check(cfg != nullptr, "configs\\system.ltx is registered");
	check(cfg && cfg->vfs != 0xffffffff, "... and comes from an archive");
	if (cfg)
		printf("  size %u bytes (stored %u), archive #%u\n", cfg->size_real, cfg->size_compressed, cfg->vfs);
	IReader* system_ltx = FS.r_open("$game_config$", "system.ltx");
	check(system_ltx != nullptr && system_ltx->length() > 0, "opened");
	if (system_ltx)
	{
		for (int i = 0; i < 10 && !system_ltx->eof(); ++i)
		{
			string1024 line;
			system_ltx->r_string(line, sizeof(line));
			printf("    %s\n", line);
		}
		FS.r_close(system_ltx);
	}
	// case-insensitive lookup, as every engine caller relies on
	IReader* again = FS.r_open("$game_config$", "SYSTEM.LTX");
	check(again != nullptr, "lookup ignores case");
	if (again)
		FS.r_close(again);

	// ---------------------------------------------------------------------------------------------
	printf("\n[4] textures and large entries\n");
	// Archive entries come in two flavours: compressed (decompressed into a heap buffer) and stored (served from a
	// pread() buffer when small, from a bounded mmap window when large). Find one of each.
	struct Pick
	{
		std::string alias, name;
		u32 raw = 0, stored = 0;
	};
	Pick small_tex, big_tex, stored_big;
	auto scan = [&](const char* alias, const char* ext)
	{
		xr_vector<LPSTR>* list = FS.file_list_open(alias, FS_ListFiles);
		if (!list)
			return;
		printf("  %zu files under %s\n", list->size(), alias);
		for (LPSTR name : *list)
		{
			const char* e = strext(name);
			if (!e || strcmp(e, ext) != 0)
				continue;
			const CLocatorAPI::file* f = FS.exist(alias, name);
			if (!f || f->vfs == 0xffffffff)
				continue;
			Pick p{alias, name, f->size_real, f->size_compressed};
			if (small_tex.name.empty() && f->size_real > 0 && f->size_real < 200 * 1024) small_tex = p;
			if (big_tex.name.empty() && f->size_real >= 1024 * 1024) big_tex = p;
			if (stored_big.name.empty() && f->size_real == f->size_compressed && f->size_real >= 300 * 1024)
				stored_big = p;
			if (!small_tex.name.empty() && !big_tex.name.empty() && !stored_big.name.empty())
				break;
		}
		FS.file_list_close(list);
	};
	scan("$game_textures$", ".dds");
	if (stored_big.name.empty())
		scan("$game_sounds$", ".ogg");
	if (stored_big.name.empty())
		scan("$game_meshes$", ".ogf");

	check(!small_tex.name.empty(), "found a small texture");
	if (!small_tex.name.empty())
	{
		IReader* t = FS.r_open(small_tex.alias.c_str(), small_tex.name.c_str());
		printf("  %s : %d bytes (stored %u)\n", small_tex.name.c_str(), t ? t->length() : -1, small_tex.stored);
		check(t && (u32)t->length() == small_tex.raw, "size matches the registry");
		if (t) FS.r_close(t);
	}
	check(!big_tex.name.empty(), "found a texture of 1 MB or more");
	if (!big_tex.name.empty())
	{
		IReader* t = FS.r_open(big_tex.alias.c_str(), big_tex.name.c_str());
		printf("  %s : %d bytes (stored %u)\n", big_tex.name.c_str(), t ? t->length() : -1, big_tex.stored);
		check(t && (u32)t->length() == big_tex.raw, "large entry size matches the registry");
		if (t)
		{
			// DDS files start with the magic "DDS "
			check(!strncmp((const char*)t->pointer(), "DDS ", 4), "bytes look like a DDS file");
			FS.r_close(t);
		}
	}
	check(!stored_big.name.empty(), "found a stored (uncompressed) entry of 300 KB or more");
	if (!stored_big.name.empty())
	{
		IReader* t = FS.r_open(stored_big.alias.c_str(), stored_big.name.c_str());
		CStreamReader* r = FS.rs_open(stored_big.alias.c_str(), stored_big.name.c_str());
		printf("  %s : %d bytes\n", stored_big.name.c_str(), t ? t->length() : -1);
		check(t && (u32)t->length() == stored_big.raw, "mmap window reader returns the full entry");
		check(r && r->length() == stored_big.raw, "stream reader reports the same size");
		if (t && r)
		{
			u64 a = hash_of_reader(t);
			u64 b = hash_of_stream(r);
			printf("  hash via IReader %016llx, via CStreamReader %016llx\n", (unsigned long long)a,
			       (unsigned long long)b);
			check(a == b, "both read paths return identical bytes");
		}
		if (t) FS.r_close(t);
		if (r) FS.r_close(r);
	}

	// ---------------------------------------------------------------------------------------------
	printf("\n[5] mixed-case paths on the real file system\n");
	{
		// The registry is lower case and '\\' separated; the disk may not be. Create Mixed\Case.TXT under the
		// run directory with OS calls, then open it through the virtual lower-case name.
		std::string dir = run_dir + "Mixed";
		make_dirs(dir);
		std::string file = dir + "/Case.TXT";
		if (FILE* f = fopen(file.c_str(), "wb")) { fputs("hello\n", f); fclose(f); }
		string_path virt;
		xr_virtual_path((run_dir + "mixed/case.txt").c_str(), virt, sizeof(virt));
		FILE* f = xr_fopen(virt, "rb");
		char buf[16] = {};
		if (f) { size_t n = fread(buf, 1, sizeof(buf) - 1, f); (void)n; fclose(f); }
		check(f && !strncmp(buf, "hello", 5), "opened Mixed/Case.TXT as mixed/case.txt");
		unlink(file.c_str());
		rmdir(dir.c_str());

		IWriter* w = FS.w_open("$app_data_root$", "smoke_out\\writetest.bin");
		check(w != nullptr, "can write into appdata");
		if (w)
		{
			w->w_u32(0xC0FFEE);
			FS.w_close(w);
			IReader* r = FS.r_open("$app_data_root$", "smoke_out\\writetest.bin");
			check(r && r->r_u32() == 0xC0FFEE, "read back what was written");
			if (r) FS.r_close(r);
			FS.file_delete("$app_data_root$", "smoke_out\\writetest.bin");
		}
	}

	// ---------------------------------------------------------------------------------------------
	printf("\n[6] timers, locks, threads\n");
	{
		// the hardware CRC must be CRC32C: crc32c("123456789") == 0xE3069283 (xrCore returns it without the final xor)
		check((crc32("123456789", 9) ^ 0xFFFFFFFFu) == 0xE3069283u, "crc32 is CRC32C");
	}
	{
		CTimer t;
		t.Start();
		Sleep(60);
		u32 ms = t.GetElapsed_ms();
		printf("  slept 60 ms, timer says %u ms (qpc freq %llu)\n", ms, (unsigned long long)CPU::qpc_freq);
		check(ms >= 55 && ms < 200, "CTimer tracks wall time");
		printf("  cpu: %s [%s], %u cores / %u threads, clk/s %llu\n", CPU::ID.model_name, CPU::ID.v_name,
		       CPU::ID.n_cores, CPU::ID.n_threads, (unsigned long long)CPU::clk_per_second);

		SharedCounter shared;
		const int threads = 4;
		for (int i = 0; i < threads; ++i)
			thread_spawn(counter_thread, "smoke", 0, &shared);
		for (int waited = 0; waited < 500; ++waited)
		{
			Sleep(10);
			xrCriticalSectionGuard guard(shared.lock);
			if (shared.value >= threads * 1000000)
				break;
		}
		xrCriticalSectionGuard guard(shared.lock);
		check(shared.value == threads * (10000 + 1000000), "4 threads x 10000 locked increments");
	}
	{
		std::atomic<int> sum{0};
		xr_parallel_for(0, 1000, [&](int i) { sum += i; });
		check(sum == 499500, "xr_parallel_for");
	}
	{
		void* p = xr_malloc(1 << 20);
		check(p && ((uintptr_t)p % 16) == 0, "allocator returns 16-byte aligned blocks");
		check(Memory.mem_usage() > 0, "heap statistics");
		xr_free(p);
	}

	printf("\n%s (%d check%s failed)\n", g_failures ? "FAILED" : "PASSED", g_failures, g_failures == 1 ? "" : "s");
	Core._destroy();
	return g_failures ? 1 : 0;
}
