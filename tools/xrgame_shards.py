#!/usr/bin/env python3
"""Generate the xrGame shard file lists (cmake/targets/xrgame_shards/<shard>.txt).

Every tracked file of src/xrGame (without vs2022/) and src/xrServerEntities is assigned to exactly one shard.
Rules (docs/ios-port/XRGAME-SHARDS.md):

  * src/xrServerEntities/**              -> script-entities
  * everything else                      -> by the Visual Studio filter of xrGame.vcxproj.filters (the project's own
                                            virtual folders), matched case-insensitively; a file the filters do not list
                                            takes the most common filter of its directory, else Core\\Common
  * files matching shared.txt            -> shared (owned by the xrgame-triage session, not by a shard)
  * mp-stub rule beats the others        -> multiplayer, GameSpy, anti-cheat, account and award files

Output paths are relative to src/ with the on-disk spelling, sorted, one per line.

    tools/xrgame_shards.py            # rewrite cmake/targets/xrgame_shards/*.txt
    tools/xrgame_shards.py --check    # exit 1 if the committed lists are stale
    tools/xrgame_shards.py --stats    # files, .cpp and lines per shard
"""
import argparse
import collections
import fnmatch
import html
import os
import re
import subprocess
import sys

ROOT = os.path.realpath(os.path.join(os.path.dirname(__file__), os.pardir))
SRC = os.path.join(ROOT, 'src')
OUT_DIR = os.path.join(ROOT, 'cmake', 'targets', 'xrgame_shards')
FILTERS = os.path.join(SRC, 'xrGame', 'xrGame.vcxproj.filters')

SHARDS = ['ai-monsters-a', 'ai-monsters-b', 'ai-core', 'nav-alife', 'script-entities', 'ui',
          'objects-items', 'objects-world', 'core-physics', 'mp-stub']
SOURCE_EXT = ('.cpp', '.c', '.h', '.hpp', '.inl', '.cxx', '.tpp')

MP = re.compile(r'(\\mp(\\|$)|Multiplayer|Games\\server\\(mp|deathmatch|artefact_hunt|capture_the_artefact|team_deathmatch)'
                r'|Games\\client\\(mp|deathmatch|team_deathmatch|artefact_hunt|capture_the_artefact)|PlayerAccounts|filetransfer'
                r'|xrGameSpyServer|GameSpy|anticheat|screenshots|award_system|SecureMessages'
                r'|UI\\GameTypes\\(CaptureTheArtefact|Deathmatch|TeamDeathmatch))', re.I)

RULES = [
    ('mp-stub', lambda k: MP.search(k)),
    ('ai-monsters-a', lambda k: k.startswith('AI\\AMonsters\\common')),
    ('ai-monsters-b', lambda k: k.startswith('AI\\AMonsters')),
    ('ai-core', lambda k: k.startswith(('AI\\AComponents', 'AI\\AGroup', 'AI\\ACover', 'AI\\AEval', 'AI\\ADebug',
                                        'AI\\ASpace', 'AI\\ASound')) or k == 'AI'),
    ('nav-alife', lambda k: k.startswith(('AI\\ANavigation', 'AI\\ALife'))),
    ('script-entities', lambda k: k.startswith('AI\\AScript')),
    ('ui', lambda k: k.startswith('UI')),
    ('objects-items', lambda k: k.startswith(('Core\\Client\\Objects\\items', 'Core\\Client\\Objects\\inventory'))),
    ('objects-world', lambda k: k.startswith('Core\\Client\\Objects')),
    ('core-physics', lambda k: k.startswith(('Core', 'Physics'))),
]


def tracked_files():
    out = subprocess.run(['git', 'ls-files', 'src/xrGame', 'src/xrServerEntities'], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout.splitlines()
    return [p[len('src/'):] for p in out
            if p.lower().endswith(SOURCE_EXT) and not p.startswith('src/xrGame/vs2022/')]


def read_filters():
    text = open(FILTERS, encoding='utf-8-sig', errors='replace').read()
    filt = {}
    for kind, path, body in re.findall(r'<(ClCompile|ClInclude)\s+Include="([^"]+)"\s*(?:/>|>(.*?)</\1>)', text, flags=re.S):
        m = re.search(r'<Filter>(.*?)</Filter>', body or '')
        p = os.path.normpath(os.path.join('xrGame', path.replace('\\', '/'))).lower()
        filt[p] = html.unescape(m.group(1)) if m else ''
    return filt


def read_shared():
    path = os.path.join(OUT_DIR, 'shared.txt')
    pats = []
    if os.path.exists(path):
        for line in open(path):
            line = line.split('#', 1)[0].strip()
            if line:
                pats.append(line.lower())
    return pats


def read_overrides():
    """pins.txt (hand-written) wins over overrides.txt (generated by --deps)."""
    out = {}
    for name in ('overrides.txt', 'pins.txt'):
        path = os.path.join(OUT_DIR, name)
        if os.path.exists(path):
            for line in open(path):
                line = line.split('#', 1)[0].strip()
                if line:
                    shard, rel = line.split(None, 1)
                    out[rel.lower()] = shard
    return out


def is_shared(rel, pats):
    low = rel.lower()
    return any(fnmatch.fnmatchcase(low, p) for p in pats)


def assign(files):
    filt = read_filters()
    pats = read_shared()
    overrides = read_overrides()
    pins = set()
    pin_path = os.path.join(OUT_DIR, 'pins.txt')
    if os.path.exists(pin_path):
        for line in open(pin_path):
            line = line.split('#', 1)[0].strip()
            if line:
                pins.add(line.split(None, 1)[1].lower())
    keyed = {}
    by_dir = collections.defaultdict(collections.Counter)
    for rel in files:
        k = filt.get(rel.lower())
        if k:
            keyed[rel] = k
            by_dir[os.path.dirname(rel.lower())][k] += 1
    result = {}
    for rel in files:
        if is_shared(rel, pats):
            result[rel] = 'shared'
            continue
        if rel.lower() in overrides and (not rel.lower().endswith(('.cpp', '.c')) or rel.lower() in pins):
            result[rel] = overrides[rel.lower()]
            continue
        k = keyed.get(rel)
        if k is None:
            c = by_dir.get(os.path.dirname(rel.lower()))
            k = c.most_common(1)[0][0] if c else 'Core\\Common'
        if rel.startswith('xrServerEntities/') and not MP.search(k):
            result[rel] = 'script-entities'
            continue
        result[rel] = next(n for n, p in RULES if p(k))
    return result


def count_lines(rel):
    try:
        with open(os.path.join(SRC, rel), 'rb') as f:
            return sum(1 for _ in f)
    except OSError:
        return 0


def render(assignment):
    groups = collections.defaultdict(list)
    for rel, shard in assignment.items():
        groups[shard].append(rel)
    return {s: ''.join(p + '\n' for p in sorted(groups.get(s, []), key=str.lower)) for s in SHARDS + ['shared']}


def header_users(build):
    """Run the preprocessor over every xrGame translation unit of the build and return
    {header (relative to src/, on-disk spelling): set of shards whose TUs include it, directly or not}."""
    import concurrent.futures
    import json
    import shlex
    with open(os.path.join(build, 'compile_commands.json')) as f:
        entries = json.load(f)
    owner = {}
    for shard in SHARDS:
        path = os.path.join(OUT_DIR, shard + '.txt')
        if os.path.exists(path):
            for line in open(path):
                owner[line.strip().lower()] = shard
    tus = []
    for e in entries:
        rel = os.path.relpath(os.path.realpath(e['file']), SRC)
        if rel.lower() in owner and rel.lower().endswith(('.cpp', '.c')):
            tus.append((owner[rel.lower()], e))

    def deps(item):
        shard, e = item
        args = shlex.split(e['command'])
        out, skip = [], 0
        for a in args:
            if skip:
                skip -= 1
                continue
            if a in ('-o', '-MT', '-MF', '-MQ'):
                skip = 1
                continue
            if a in ('-MD', '-MMD', '-MP', '-c'):
                continue
            out.append(a)
        out += ['-M', '-MG', '-w', '-ferror-limit=0']
        p = subprocess.run(out, cwd=e['directory'], capture_output=True, text=True, errors='replace')
        files = set()
        text = p.stdout.replace('\\\n', ' ')
        for tok in re.findall(r'(?:\\ |\S)+', text.split(': ', 1)[1] if ': ' in text else ''):
            tok = tok.replace('\\ ', ' ')
            if os.path.exists(tok):
                files.add(os.path.relpath(os.path.realpath(tok), ROOT))
        return shard, files

    users = collections.defaultdict(set)
    per_shard = collections.defaultdict(set)
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as pool:
        for shard, files in pool.map(deps, tus):
            for r in files:
                per_shard[shard].add(r)
                if r.startswith('src/'):
                    users[r[len('src/'):]].add(shard)
    return users, per_shard


def write_deps_report(path, per_shard, owner_of):
    """Which modules' headers and which other shards' headers each shard's translation units include."""
    mods = ['xrEngine', 'xrCore', 'Include', 'Common', 'xrPhysics', 'xrCDB', 'xrNetServer', 'xrSound', 'xrParticles',
            'xrXMLParser', 'xrServerEntities', 'Layers', '3rd party', 'sdk', 'external']
    out = ['| shard | ' + ' | '.join(mods) + ' |', '|---|' + '---:|' * len(mods)]
    for shard in SHARDS:
        row = []
        for m in mods:
            prefix = ('src/' + m + '/') if m not in ('sdk', 'external') else (m + '/')
            if m == 'xrServerEntities':
                row.append(str(sum(1 for f in per_shard[shard] if f.startswith('src/xrServerEntities/')
                                   and owner_of(f[4:]) != shard)))
            else:
                row.append(str(sum(1 for f in per_shard[shard] if f.startswith(prefix) and f.lower().endswith(('.h', '.hpp', '.inl')))))
        out.append('| %s | %s |' % (shard, ' | '.join(row)))
    out += ['', '| shard \\ header owner | ' + ' | '.join(SHARDS + ['shared']) + ' |', '|---|' + '---:|' * (len(SHARDS) + 1)]
    for shard in SHARDS:
        counts = collections.Counter()
        for f in per_shard[shard]:
            if f.startswith(('src/xrGame/', 'src/xrServerEntities/')) and f.lower().endswith(('.h', '.hpp', '.inl')):
                counts[owner_of(f[4:])] += 1
        out.append('| %s | %s |' % (shard, ' | '.join(str(counts.get(o, 0)) if o != shard else '(%d)' % counts.get(o, 0)
                                                        for o in SHARDS + ['shared'])))
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--stats', action='store_true')
    ap.add_argument('--report', metavar='FILE', help='with --deps: also write the shard dependency tables (markdown)')
    ap.add_argument('--deps', metavar='BUILD_DIR',
                    help='recompute overrides.txt: headers only one shard includes (transitively) belong to that shard')
    args = ap.parse_args()

    if args.deps:
        users, per_shard = header_users(os.path.realpath(args.deps))
        base = assign(tracked_files())
        if args.report:
            write_deps_report(args.report, per_shard, lambda r: base.get(r) or next(
                (v for k, v in base.items() if k.lower() == r.lower()), '?'))
        lines = []
        multi = single = unused = 0
        for rel, shard in sorted(base.items(), key=lambda kv: kv[0].lower()):
            if rel.lower().endswith(('.cpp', '.c')) or shard == 'shared':
                continue
            u = users.get(rel)
            if not u:
                unused += 1
            elif len(u) == 1:
                single += 1
                (only,) = u
                if only != shard:
                    lines.append('%s %s\n' % (only, rel))
            else:
                multi += 1
        with open(os.path.join(OUT_DIR, 'overrides.txt'), 'w') as f:
            f.write('# Headers that only one shard includes (transitively, in the current build) belong to that shard even when the\n'
                    '# project filter says otherwise. Generated by tools/xrgame_shards.py --deps <build dir>; one `shard path` per line.\n')
            f.writelines(lines)
        print('headers: %d single-shard (%d reassigned), %d multi-shard, %d never included' % (single, len(lines), multi, unused))
        return 0

    assignment = assign(tracked_files())
    if args.stats:
        stats = collections.defaultdict(lambda: [0, 0, 0])
        for rel, shard in assignment.items():
            s = stats[shard]
            s[0] += 1
            s[1] += rel.lower().endswith(('.cpp', '.c'))
            s[2] += count_lines(rel)
        print('%-16s %6s %6s %9s' % ('shard', 'files', 'cpp+c', 'lines'))
        for shard in SHARDS + ['shared']:
            s = stats[shard]
            print('%-16s %6d %6d %9d' % (shard, *s))
        return 0

    rendered = render(assignment)
    stale = []
    os.makedirs(OUT_DIR, exist_ok=True)
    for shard, text in rendered.items():
        path = os.path.join(OUT_DIR, shard + '.txt')
        old = open(path).read() if os.path.exists(path) else None
        if shard == 'shared':
            continue  # shared.txt is the hand-maintained pattern list that feeds this script
        if old != text:
            stale.append(shard)
            if not args.check:
                with open(path, 'w') as f:
                    f.write(text)
    if args.check:
        if stale:
            print('stale shard lists: ' + ', '.join(stale) + ' (run tools/xrgame_shards.py)')
            return 1
        return 0
    # the resolved shared set is informational
    with open(os.path.join(OUT_DIR, 'shared.files'), 'w') as f:
        f.write(rendered['shared'])
    print('wrote %d shard lists to %s' % (len(SHARDS), os.path.relpath(OUT_DIR, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
