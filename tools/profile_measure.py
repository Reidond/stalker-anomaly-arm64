#!/usr/bin/env python3
"""Measurements for the device graphics profiles (docs/ios-port/SETTINGS.md).

    python3 -I tools/profile_measure.py script --save h_cordon > run.script       # a --script timeline
    python3 -I tools/profile_measure.py summarize shell.log [shell2.log ...]      # markdown table

`script` loads a save in the Cordon and, for each graphics mode, plays the same five scenes: outdoors at noon, outdoors in rain, inside
the trader's bunker, the Rookie village (a busy base) at noon, and the village at night with the flashlight on. A scene is `--seconds`
long (default 30) after `--settle` seconds (default 10) that the shell log's 10 s windows do not count. `summarize` reads the shell
log of such a run (anomaly-shell.log; on the iPad `tools/ios/ipad.sh logs`) and prints one row per mode and scene: the frame rate
(mean of the windows, and the slowest window), the CPU time of a frame, the GPU time, draws, the memory the OS charges (peak),
the Metal memory, and the thermal state. A second table gives the frame intervals (the time between the starts of two frames, from the
shell log's "frame intervals" line): the share of the frames at about 8, 17, 25, 33 ms ..., which shows whether a capped frame rate is even
(40 fps on a 120 Hz panel is all at 25 ms; on a 60 Hz one it is split between 17 and 33 ms).
"""
import argparse
import re
import sys

SCENES = [
    ("field", ['xr_harness.env(12,0,"w_clear1")', "xr_harness.tp(-2.8,2.8,82.7,200)"]),
    ("rain", ['xr_harness.env(9,0,"w_rain3")', "xr_harness.tp(-2.8,2.8,82.7,200)"]),
    ("bunker", ['xr_harness.env(14,0,"w_rain2")', 'xr_harness.tp_story("esc_m_trader",90)']),
    ("village", ['xr_harness.env(12,0,"w_clear1")', "xr_harness.tp(-215,-7.5,-40.6,0)"]),
    ("night", ['xr_harness.env(0,30,"w_clear2")', "xr_harness.tp(-215,-8.5,-40.6,0)", "xr_harness.torch(true)", "xr_harness.torch(true)"]),
]


def make_script(args):
    """One launch per mode: the mode is set before the level loads, so the profile's settings are in place from the start (a mode
    switch with `vid_restart` in the middle of a run would mix the two modes' memory and pipelines)."""
    out = ["# standalone", "# generated by tools/profile_measure.py script", "1 console r_screenshot_mode png"]
    modes = args.modes.split(",")
    if len(modes) == 1:
        out.append("1.2 console gfx_mode %s" % modes[0])
    if args.unlimited:  # no frame cap: what the device could do (needs --unlocked-graphics)
        out.append("1.4 console gfx_fps unlimited")
    elif args.fps:  # a cap that the display does not show evenly is refused unless the run is --unlocked-graphics
        out.append("1.4 console gfx_fps %d" % args.fps)
    for k, c in enumerate(args.console):  # more settings, e.g. "r__upscaler metalfx" (--unlocked-graphics: the profile locks them)
        out.append("%g console %s" % (1.5 + 0.05 * k, c))
    out.append("2 console start server(%s/single/alife/load) client(localhost)" % args.save)
    out.append("3 waitlevel 300 l01_escape")
    t = 3.0
    for i in range(6):  # the loading screen waits for a key
        t += 2
        out.append("%g key Left Shift" % t)
    t += 4
    if args.soak > 0:
        # heat the device first: the village at noon (the busiest scene), so that the scenes are measured warm (the thermal column
        # of the table says which state each window ran in; an iPad goes from Nominal to Serious after a minute or two of load)
        for k, c in enumerate(dict(SCENES)["village"]):
            out.append("%g console run_string %s" % (t + k * 0.5, c))
        out.append("%g log SOAK begin %g s" % (t + 1, args.soak))
        t += args.soak
        out.append("%g log SOAK end" % t)
    for mode in modes:
        if len(modes) > 1:  # a switch in the middle of a run: the menu's path, with its video restart
            out.append("%g console gfx_mode %s" % (t, mode))
            out.append("%g console vid_restart" % (t + 0.5))
            t += 10
        for name, commands in SCENES:
            for k, c in enumerate(commands):
                out.append("%g console run_string %s" % (t + k * 0.5, c))
            t += args.settle
            out.append("%g log MEAS %s %s begin" % (t, mode, name))
            t += args.seconds
            out.append("%g log MEAS %s %s end" % (t, mode, name))
    out.append("%g quit" % (t + 2))
    print("\n".join(out))


def make_sweep(args):
    """One launch, one scene, several variants of the profile's settings: each variant resets the profile (a switch to the other mode and
    back), applies its overrides, restarts the video and is measured for --seconds. Needs --unlocked-graphics."""
    scene = dict(SCENES)[args.scene]
    out = ["# standalone", "# generated by tools/profile_measure.py sweep", "1 console r_screenshot_mode png",
           "1.2 console gfx_mode quality", "1.4 console gfx_fps unlimited",
           "2 console start server(%s/single/alife/load) client(localhost)" % args.save, "3 waitlevel 300 l01_escape"]
    t = 3.0
    for i in range(6):
        t += 2
        out.append("%g key Left Shift" % t)
    t += 4
    for k, c in enumerate(scene):
        out.append("%g console run_string %s" % (t + k * 0.5, c))
    t += 6
    for name, overrides in args.variants:
        out.append("%g console gfx_mode performance" % t)
        out.append("%g console gfx_mode quality" % (t + 0.2))
        for k, o in enumerate(overrides):
            out.append("%g console %s" % (t + 0.4 + 0.1 * k, o))
        out.append("%g console vid_restart" % (t + 1.5))
        t += 11
        out.append("%g log MEAS sweep %s begin" % (t, name))
        t += args.seconds
        out.append("%g log MEAS sweep %s end" % (t, name))
    out.append("%g quit" % (t + 2))
    print("\n".join(out))


STAT = re.compile(r"^\[\s*([\d.]+)\] anomaly: ([\d.]+) fps \((\d+) frames in ([\d.]+) s\), frame cpu ([\d.]+) ms avg ([\d.]+) max, gpu ([\d.]+) ms, "
                  r"footprint (\d+) MB \(peak (\d+)\), available (\d+) MB, thermal (\w+)")
METAL = re.compile(r"^\[\s*([\d.]+)\] anomaly: metal: gpu ([\d.]+) ms/frame, cpu ([\d.]+) ms/frame \(blocked ([\d.]+)\), (\d+) draws, ([\d.]+) passes/frame; "
                   r"textures (\d+) MB \(render targets (\d+) MB\), buffers (\d+) MB, allocated (\d+) MB")
INTERVALS = re.compile(r"^\[\s*([\d.]+)\] anomaly: frame intervals \([^)]*\): ((?:[\d.]+ ){11}[\d.]+); longest ([\d.]+) ms")
# the marker is logged twice ("script t=161.0 log MEAS ..." and "script: MEAS ..."); a log line from another thread can split one of them
MARK = re.compile(r"^\[\s*([\d.]+)\] anomaly: script(?: t=[\d.]+ log|:) MEAS (\w+) (\w+) (begin|end)")


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def load_contention(path):
    """seconds since the run started -> number of other `anomaly` processes (tools/render_harness/measure_profile.sh)"""
    out = []
    if path:
        for line in open(path):
            parts = line.split()
            if len(parts) == 2:
                out.append((float(parts[0]), int(parts[1])))
    return out


def summarize(paths, contention_path=None):
    rows, interval_rows = [], []
    contention = load_contention(contention_path)
    for path in paths:
        stats, metals, marks, gaps = [], [], {}, []
        for line in open(path, errors="replace"):
            m = INTERVALS.match(line)
            if m:
                gaps.append((float(m.group(1)), [float(x) for x in m.group(2).split()], float(m.group(3))))
                continue
            m = STAT.match(line)
            if m:
                stats.append((float(m.group(1)), [float(x) if i not in (10,) else x for i, x in enumerate(m.groups())]))
                continue
            m = METAL.match(line)
            if m:
                metals.append((float(m.group(1)), [float(x) for x in m.groups()]))
                continue
            m = MARK.match(line)
            if m:
                marks[(m.group(2), m.group(3), m.group(4))] = float(m.group(1))
        keys = sorted({(a, b) for a, b, _ in marks if (a, b, "begin") in marks}, key=lambda k: marks[(k[0], k[1], "begin")])
        for mode, scene in keys:
            begin, end = marks.get((mode, scene, "begin")), marks.get((mode, scene, "end"))
            if begin is None or end is None:
                continue
            w = [(t, v) for t, v in stats if t - v[3] >= begin - 0.6 and t <= end + 0.6]
            m = [v for t, v in metals if begin - 0.6 <= t - 5 and t <= end + 0.6]
            if not w:
                continue
            # the shell log's clock starts about a second after the sampler's: a window is contended if any sample in it, give or take 2 s, saw another game
            clean = [x for x in w if not any(n > 0 for ts, n in contention if x[0] - x[1][3] - 2 <= ts <= x[0] + 2)]
            note = "" if len(clean) == len(w) else " (contended: %d of %d windows)" % (len(w) - len(clean), len(w))
            if clean:
                w = clean
            else:
                note = " (contended)"
            # the interval line of each window follows its fps line within a moment
            g = [(buckets, longest) for t, _ in w for tg, buckets, longest in gaps if t <= tg <= t + 0.5]
            if g:
                share = [mean([b[i] for b, _ in g]) for i in range(12)]
                # <6 6-11 11-14 14-19 19-22 22-28 28-31 31-37 37-45 45-55 55-100 >=100
                interval_rows.append((mode, scene, len(g), share[0] + share[1] + share[2], share[3], share[4], share[5], share[6], share[7],
                                      share[8] + share[9], share[10] + share[11], max(longest for _, longest in g)))
            rows.append((mode, scene + note, len(w),
                         mean([v[1] for _, v in w]), min(v[1] for _, v in w),
                         mean([v[4] for _, v in w]), mean([x[1] for x in m]), mean([x[4] for x in m]),
                         max(v[8] for _, v in w), mean([x[6] + 0 for x in m]) if m else float("nan"),
                         mean([x[7] for x in m]), w[-1][1][10]))
    print("| Mode | Scene | windows | fps | slowest | CPU ms | GPU ms | draws | footprint MB | textures MB | render targets MB | thermal |")
    print("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|")
    for r in rows:
        print("| %s | %s | %d | %.1f | %.1f | %.1f | %.1f | %.0f | %.0f | %.0f | %.0f | %s |" % r)
    if interval_rows:
        print()
        print("Frame intervals, % of the frames by the time since the previous frame started:")
        print()
        print("| Mode | Scene | windows | under 14 ms | 14 to 19 (17) | 19 to 22 | 22 to 28 (25) | 28 to 31 | 31 to 37 (33) | 37 to 55 | over 55 | longest ms |")
        print("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
        for r in interval_rows:
            print("| %s | %s | %d | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.0f |" % r)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--save", required=True, help="the save to load (Mac: h_cordon from run_scene.sh --newgame; iPad: ipad_test)")
    s.add_argument("--modes", default="quality", help="one mode per launch (the default), or a comma list: switched in the middle of one run")
    s.add_argument("--seconds", type=float, default=34)
    s.add_argument("--settle", type=float, default=10)
    s.add_argument("--soak", type=float, default=0, help="seconds to stand in the village first, to measure warm (default 0: cool)")
    s.add_argument("--unlimited", action="store_true", help="run without the profile's frame cap (the run needs --unlocked-graphics)")
    s.add_argument("--fps", type=int, default=0, help="a frame cap of this many fps instead of the mode's (an uneven one needs --unlocked-graphics)")
    s.add_argument("--console", action="append", default=[], metavar="CMD", help="a console command to run before the level loads (repeatable)")
    w = sub.add_parser("sweep")
    w.add_argument("--save", required=True)
    w.add_argument("--scene", default="rain", choices=[n for n, _ in SCENES])
    w.add_argument("--seconds", type=float, default=22)
    w.add_argument("--variant", action="append", default=[], metavar="NAME=cmd;cmd",
                   help="a variant: its name, then console commands separated by ';' (empty: the profile as it is). Repeatable")
    m = sub.add_parser("summarize")
    m.add_argument("logs", nargs="+")
    m.add_argument("--contention", help="the sampler's file from measure_profile.sh")
    args = ap.parse_args()
    if args.cmd == "script":
        make_script(args)
    elif args.cmd == "sweep":
        args.variants = []
        for v in args.variant or ["baseline="]:
            name, _, cmds = v.partition("=")
            args.variants.append((name, [c.strip() for c in cmds.split(";") if c.strip()]))
        make_sweep(args)
    else:
        summarize(args.logs, args.contention)


if __name__ == "__main__":
    sys.exit(main())
