#!/usr/bin/env python3
"""Measurements for the device graphics profiles (docs/ios-port/SETTINGS.md).

    python3 -I tools/profile_measure.py script --save h_cordon > run.script       # a --script timeline
    python3 -I tools/profile_measure.py summarize shell.log [shell2.log ...]      # markdown table

`script` loads a save in the Cordon and, for each graphics mode, plays the same five scenes: outdoors at noon, outdoors in rain, inside
the trader's bunker, the Rookie village (a busy base) at noon, and the village at night with the flashlight on. A scene is `--seconds`
long (default 30) after `--settle` seconds (default 10) that the shell log's 10 s windows do not count. `summarize` reads the shell
log of such a run (anomaly-shell.log; on the iPad `tools/ios/ipad.sh logs`) and prints one row per mode and scene: the frame rate
(mean of the windows, and the slowest window), the CPU time of a frame, the GPU time, draws, the memory the OS charges (peak),
the Metal memory, and the thermal state.
"""
import argparse
import re
import sys

SCENES = [
    ("field", ['xr_harness.env(12,0,"w_clear1")', "xr_harness.tp(-2.8,2.8,82.7,200)"]),
    ("rain", ['xr_harness.env(9,0,"w_rain3")', "xr_harness.tp(-2.8,2.8,82.7,200)"]),
    ("bunker", ['xr_harness.env(14,0,"w_rain2")', 'xr_harness.tp_story("esc_m_trader",90)']),
    ("village", ['xr_harness.env(12,0,"w_clear1")', "xr_harness.tp(-215,-7.5,-40.6,0)"]),
    ("night", ['xr_harness.env(0,30,"w_clear2")', "xr_harness.tp(-215,-8.5,-40.6,0)", "xr_harness.torch(true)", "xr_harness.torch(true)"]),
]


def make_script(args):
    out = ["# standalone", "# generated by tools/profile_measure.py script", "1 console r_screenshot_mode png"]
    out.append("2 console start server(%s/single/alife/load) client(localhost)" % args.save)
    out.append("3 waitlevel 300 l01_escape")
    t = 3.0
    for i in range(6):  # the loading screen waits for a key
        t += 2
        out.append("%g key Left Shift" % t)
    t += 2
    if args.unlimited:  # no frame cap: what the device could do (needs --unlocked-graphics)
        out.append("%g console gfx_fps unlimited" % t)
        t += 1
    for mode in args.modes.split(","):
        out.append("%g console gfx_mode %s" % (t, mode))
        out.append("%g console vid_restart" % (t + 0.5))
        t += 10
        for name, commands in SCENES:
            for k, c in enumerate(commands):
                out.append("%g console run_string %s" % (t + k * 0.5, c))
            t += args.settle
            out.append("%g log MEAS %s %s begin" % (t, mode, name))
            t += args.seconds
            out.append("%g log MEAS %s %s end" % (t, mode, name))
    out.append("%g quit" % (t + 2))
    print("\n".join(out))


STAT = re.compile(r"^\[\s*([\d.]+)\] anomaly: ([\d.]+) fps \((\d+) frames in ([\d.]+) s\), frame cpu ([\d.]+) ms avg ([\d.]+) max, gpu ([\d.]+) ms, "
                  r"footprint (\d+) MB \(peak (\d+)\), available (\d+) MB, thermal (\w+)")
METAL = re.compile(r"^\[\s*([\d.]+)\] anomaly: metal: gpu ([\d.]+) ms/frame, cpu ([\d.]+) ms/frame \(blocked ([\d.]+)\), (\d+) draws, ([\d.]+) passes/frame; "
                   r"textures (\d+) MB \(render targets (\d+) MB\), buffers (\d+) MB, allocated (\d+) MB")
MARK = re.compile(r"^\[\s*([\d.]+)\] anomaly: script: MEAS (\w+) (\w+) (begin|end)")


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def load_contention(path):
    """seconds since the run started -> number of other `anomaly` processes (tools/render_harness/measure_profile.sh)"""
    out = []
    if path:
        for line in open(path):
            parts = line.split()
            if len(parts) == 2:
                out.append((float(parts[0]), int(parts[1])))
    return out


def summarize(paths, contention_path=None):
    rows = []
    contention = load_contention(contention_path)
    for path in paths:
        stats, metals, marks = [], [], {}
        for line in open(path, errors="replace"):
            m = STAT.match(line)
            if m:
                stats.append((float(m.group(1)), [float(x) if i not in (10,) else x for i, x in enumerate(m.groups())]))
                continue
            m = METAL.match(line)
            if m:
                metals.append((float(m.group(1)), [float(x) for x in m.groups()]))
                continue
            m = MARK.match(line)
            if m:
                marks[(m.group(2), m.group(3), m.group(4))] = float(m.group(1))
        keys = sorted({(a, b) for a, b, _ in marks if (a, b, "begin") in marks}, key=lambda k: marks[(k[0], k[1], "begin")])
        for mode, scene in keys:
            begin, end = marks.get((mode, scene, "begin")), marks.get((mode, scene, "end"))
            if begin is None or end is None:
                continue
            w = [(t, v) for t, v in stats if t - v[3] >= begin - 0.6 and t <= end + 0.6]
            m = [v for t, v in metals if begin - 0.6 <= t - 5 and t <= end + 0.6]
            if not w:
                continue
            # the shell log's clock starts about a second after the sampler's: a window is contended if any sample in it, give or take 2 s, saw another game
            clean = [x for x in w if not any(n > 0 for ts, n in contention if x[0] - x[1][3] - 2 <= ts <= x[0] + 2)]
            note = "" if len(clean) == len(w) else " (contended: %d of %d windows)" % (len(w) - len(clean), len(w))
            if clean:
                w = clean
            else:
                note = " (contended)"
            rows.append((mode, scene + note, len(w),
                         mean([v[1] for _, v in w]), min(v[1] for _, v in w),
                         mean([v[4] for _, v in w]), mean([x[1] for x in m]), mean([x[4] for x in m]),
                         max(v[8] for _, v in w), mean([x[6] + 0 for x in m]) if m else float("nan"),
                         mean([x[7] for x in m]), w[-1][1][10]))
    print("| Mode | Scene | windows | fps | slowest | CPU ms | GPU ms | draws | footprint MB | textures MB | render targets MB | thermal |")
    print("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|")
    for r in rows:
        print("| %s | %s | %d | %.1f | %.1f | %.1f | %.1f | %.0f | %.0f | %.0f | %.0f | %s |" % r)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--save", required=True, help="the save to load (Mac: h_cordon from run_scene.sh --newgame; iPad: ipad_test)")
    s.add_argument("--modes", default="quality,performance")
    s.add_argument("--seconds", type=float, default=30)
    s.add_argument("--settle", type=float, default=10)
    s.add_argument("--unlimited", action="store_true", help="run without the profile's frame cap (the run needs --unlocked-graphics)")
    m = sub.add_parser("summarize")
    m.add_argument("logs", nargs="+")
    m.add_argument("--contention", help="the sampler's file from measure_profile.sh")
    args = ap.parse_args()
    if args.cmd == "script":
        make_script(args)
    else:
        summarize(args.logs, args.contention)


if __name__ == "__main__":
    sys.exit(main())
