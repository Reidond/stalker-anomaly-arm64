// r4_shader_warmup: runs the shaders the R4 renderer requests through the Metal port's D3DCompile path and reports
// pass/fail and timings.
//
//   r4_shader_warmup [--game-dir <dir>] [--run-dir <dir>] [--passes N] [--cold] [--jobs N] [--filter <text>]
//                    [--no-metal] [--no-skin] [--json <file>] [--dump-msl <dir>] [--list] [--strict]
//
// Why not CRender::shader_compile itself: it is a member of CRender, which needs the whole engine (xrEngine's Device,
// console, resource manager, ...). docs/ios-port/RENDERER.md lists the 244 symbols the R4 archive still needs from
// xrEngine, xrCDB, xrParticles and xrGame. What this tool keeps from the real thing:
//   * the macro list and shader-cache id: r4_shader_macros.inl, the block CRender::shader_compile includes, run with
//     the renderer's default settings (r4_macros.cpp),
//   * the shader sources and includes through xrCore's file system, like R4's `includer` (shaders.db0 is mounted),
//   * D3DCompile, D3DReflect, D3DGetInputSignatureBlob and Create{Vertex,Pixel,Compute}Shader of the Metal shim, and
//     with them ShaderXlat, the container and the Metal library compile,
//   * R_constant_table::parse's expectations of the reflection (dx10r_constants.cpp), checked on every shader.
//
// The requests are what the engine can ask for with the stock data: r_Pass("vs", "ps") calls in the R4 blenders and the
// shader:begin("vs", "ps") lines of the r3 .s scripts; vertex shaders that use SKIN_* also in the five skinning
// variants. Names that exist in neither shaders.db0 nor a loose gamedata folder are reported as missing, not failed.
