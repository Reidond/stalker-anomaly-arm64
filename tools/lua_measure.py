#!/usr/bin/env python3
"""Lua cost measurements (docs/ios-port/LUA-PERF.md): the share of the frame spent in Lua, per graphics mode and place, and the load times.

    python3 -I tools/lua_measure.py script --save h_cordon --mode quality > run.script     # a --script timeline (run with -dbg -lua_perf)
    python3 -I tools/lua_measure.py script --save h_cordon --mode quality --profile > prof.script   # the same places, with the sampling profiler
    python3 -I tools/lua_measure.py summarize --engine engine.log --shell shell.log        # markdown tables

`script` loads a save in the Cordon and plays the places of tools/profile_measure.py (the open field, the Rookie village) and the Bar
(`jump_to_level l05_bar`, a second level load): a place is `--seconds` long (default 34) after `--settle` seconds (default 10). The
engine's `lua_perf mark` lines the timers' report per place; the `MEAS` log lines are the shell log's marks, which `profile_measure.py
summarize` reads for the frame rate, the CPU and GPU times and the thermal state. A timer run and a profiler run are separate launches (the
profiler's hook slows the interpreter a little, so a profiler run does not time anything).

`summarize` reads the engine log (the `[lua-perf]`, `[lua-load]`, `[lua-prof]` lines) and the shell log (load times: the start of a load
to `level ready`) and prints the tables.
"""
import argparse
import re
import sys

# the places: (name, level, console commands). The village and the field are in the Cordon (tools/profile_measure.py).
PLACES = {
    "field": ("l01_escape", ['xr_harness.env(12,0,"w_clear1")', "xr_harness.tp(-2.8,2.8,82.7,200)"]),
    "village": ("l01_escape", ['xr_harness.env(12,0,"w_clear1")', "xr_harness.tp(-215,-7.5,-40.6,0)"]),
    "bar": ("l05_bar", ['xr_harness.env(12,0,"w_clear1")']),
}
BAR_LEVEL = "l05_bar"


def make_script(args):
    out = ["# standalone", "# generated by tools/lua_measure.py script"]
    out.append("1 console r_screenshot_mode png")
    if args.mode:
        out.append("1.2 console gfx_mode %s" % args.mode)
    if args.fps:
        out.append("1.4 console gfx_fps %d" % args.fps)
    for k, c in enumerate(args.console):
        out.append("%g console %s" % (1.5 + 0.05 * k, c))
    if args.profile:
        out.append("1.8 console lua_profile on %d" % args.interval)
    else:
        out.append("1.8 console lua_perf on")
    out.append("2 console start server(%s/single/alife/load) client(localhost)" % args.save)
    out.append("3 waitlevel 300 l01_escape")
    t = 3.0
    for i in range(args.keys):  # the loading screen waits for a key
        t += 1
        out.append("%g key Left Shift" % t)
    t += 3
    level = "l01_escape"
    if args.soak > 0:
        for k, c in enumerate(PLACES["village"][1]):
            out.append("%g console run_string %s" % (t + k * 0.5, c))
        out.append("%g log SOAK begin %g s" % (t + 1, args.soak))
        t += args.soak
        out.append("%g log SOAK end" % t)
    for place in args.places.split(","):
        want_level, commands = PLACES[place]
        if want_level != level:
            # a level change: the jump is timed from the console command to `level ready` (the shell log)
            out.append("%g console jump_to_level %s" % (t, want_level))
            out.append("%g waitlevel 300 %s" % (t + 1, want_level))
            t += 1
            for i in range(args.keys):
                t += 1
                out.append("%g key Left Shift" % t)
            t += 3
            level = want_level
            out.append("%g log LEVEL %s" % (t, want_level))
        for k, c in enumerate(commands):
            out.append("%g console run_string %s" % (t + k * 0.5, c))
        t += 1
        label = "%s_%s" % (args.mode or "mode", place)
        if args.profile:
            out.append("%g console lua_profile reset settle_%s" % (t, place))
        else:
            out.append("%g console lua_perf mark settle_%s" % (t, place))
        t += args.settle
        out.append("%g log MEAS %s %s begin" % (t, args.mode or "mode", place))
        if args.profile:
            out.append("%g console lua_profile reset %s" % (t, label))
        else:
            out.append("%g console lua_perf mark %s" % (t, label))
        t += args.seconds
        out.append("%g log MEAS %s %s end" % (t, args.mode or "mode", place))
        if args.profile:
            out.append("%g console lua_profile report %d" % (t, args.top))
        else:
            out.append("%g console lua_perf mark after_%s" % (t, place))
    out.append("%g quit" % (t + 2))
    print("\n".join(out))


KV = re.compile(r"(\w+)=([^\s]+)")
PERF = re.compile(r"^\* \[lua-perf\] label=(\S+) why=(\S+) (.*)$")
WATCH = re.compile(r"^\* \[lua-perf\] label=(\S+) watch \(ms/frame / calls/frame\):(.*)$")
LOAD = re.compile(r"^\* \[lua-load\] (\S+) (.*)$")
PROF_HEAD = re.compile(r"^\* \[lua-prof\] label=(\S+) samples=(\d+) interval_ms=(\d+) interp=([\d.]+)% cfunc=([\d.]+)% gc=([\d.]+)% jit=([\d.]+)% native=([\d.]+)%")
PROF_ROW = re.compile(r"^\* \[lua-prof\] label=(\S+) (self|incl) #(\d+) (.*)$")
PROF_FILE = re.compile(r"^\* \[lua-prof\] label=(\S+) file #(\d+) ([\d.]+)% (\S+)$")
SHELL_STEP = re.compile(r"^\[\s*([\d.]+)\] anomaly: script t=[\d.]+ (console|click) (.*)$")
SHELL_READY = re.compile(r"^\[\s*([\d.]+)\] anomaly: script: level ready after ([\d.]+) s")
SHELL_WAIT = re.compile(r"^\[\s*([\d.]+)\] anomaly: script t=[\d.]+ waitlevel")


def parse_kv(text):
    return {k: v for k, v in KV.findall(text)}


def summarize(args):
    rows, loads, watches, prof_heads, prof_rows, prof_files = [], [], [], {}, {}, {}
    if args.engine:
        for line in open(args.engine, errors="replace"):
            line = line.rstrip("\n")
            m = WATCH.match(line)
            if m:
                watches.append((m.group(1), m.group(2).strip()))
                continue
            m = PERF.match(line)
            if m:
                kv = parse_kv(m.group(3))
                kv["label"], kv["why"] = m.group(1), m.group(2)
                if kv.get("frames", "0") != "0":
                    rows.append(kv)
                continue
            m = LOAD.match(line)
            if m:
                kv = parse_kv(m.group(2))
                kv["why"] = m.group(1)
                loads.append(kv)
                continue
            m = PROF_HEAD.match(line)
            if m:
                prof_heads[m.group(1)] = m.groups()[1:]
                continue
            m = PROF_ROW.match(line)
            if m:
                prof_rows.setdefault(m.group(1), []).append((m.group(2), m.group(3), m.group(4)))
                continue
            m = PROF_FILE.match(line)
            if m:
                prof_files.setdefault(m.group(1), []).append((m.group(2), m.group(3), m.group(4)))
    wanted = [r for r in rows if not r["label"].startswith(("settle_", "after_", "run"))]
    # a period cut by the 30 s interval and its short tail under one label: keep the one with the frames
    best = {}
    for r in wanted:
        if r["label"] not in best or int(r["frames"]) > int(best[r["label"]]["frames"]):
            best[r["label"]] = r
    wanted = [r for r in wanted if best[r["label"]] is r]
    if wanted:
        print("| Place | frames | frame ms (p95) | Lua ms | Lua CPU ms | Lua p50 / p95 / max | Lua share % | scheduler | binders | A-Life | callbacks | other | GC | calls/frame | other threads ms | GC thread ms |")
        print("|---|---:|---|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
        for r in wanted:
            print("| %s | %s | %s (%s) | %s | %s | %s / %s / %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                r["label"], r["frames"], r["frame_ms"], r["frame_p95"], r["lua_ms"], r.get("lua_cpu", "-"), r["lua_p50"], r["lua_p95"], r["lua_max"], r["share"],
                r["sched"], r["binder"], r["alife"], r["cb"], r["other"], r["gc"], r["calls"], r.get("off_main", "0"), r.get("off_gc", "0")))
        print()
    if watches:
        shown = [w for w in watches if not w[0].startswith(("settle_", "after_", "run"))]
        if shown:
            print("Callbacks (`SendScriptCallback` by name, ms per frame / calls per frame), the heaviest first:")
            print()
            for label, text in shown:
                print("- %s: %s" % (label, text))
            print()
    if loads:
        print("| Load | scripts | MB | total ms | file read ms | compile / cache ms | run ms | cache |")
        print("|---|---:|---:|---:|---:|---:|---:|---|")
        for l in loads:
            print("| %s | %s | %s | %s | %s | %s | %s | %s: %s hits, %s misses, %s stale, %s stored |" % (
                l["why"], l["files"], l["mb"], l["total_ms"], l["read_ms"], l["compile_ms"], l["run_ms"], l["cache"], l["hit"], l["miss"], l["stale"], l["stored"]))
        print()
    if args.shell:
        steps, ready = [], []
        for line in open(args.shell, errors="replace"):
            m = SHELL_STEP.match(line)
            if m and ("start server" in m.group(3) or "jump_to_level" in m.group(3) or m.group(2) == "click"):
                steps.append((float(m.group(1)), m.group(3).strip()))
            m = SHELL_READY.match(line)
            if m:
                ready.append(float(m.group(1)))
        if ready:
            print("| Level load | from | seconds |")
            print("|---|---|---:|")
            for t in ready:
                prior = [s for s in steps if s[0] <= t]
                if prior:
                    start = prior[-1]
                    print("| %s | %s | %.1f |" % ("level ready", start[1][:50], t - start[0]))
            print()
    for label in prof_heads:
        samples, interval, i, c, g, j, n = prof_heads[label]
        print("Profile %s: %s samples of %s ms, interpreter %s%%, C functions %s%%, GC %s%% (native engine code between calls: %s%%)" % (label, samples, interval, i, c, g, n))
        print()
        print("| self % | (interp / C / GC) | incl % | function |")
        print("|---:|---|---:|---|")
        for kind, rank, text in prof_rows.get(label, []):
            if kind == "self":
                m = re.match(r"([\d.]+)% \(interp ([\d.]+) c ([\d.]+) gc ([\d.]+)\) incl ([\d.]+)%\s+(.*)$", text)
                if m:
                    print("| %s | %s / %s / %s | %s | %s |" % (m.group(1), m.group(2), m.group(3), m.group(4), m.group(5), m.group(6).replace("|", "\\|")))
        print()
        print("| incl % | self % | function |")
        print("|---:|---:|---|")
        for kind, rank, text in prof_rows.get(label, []):
            if kind == "incl":
                m = re.match(r"([\d.]+)% self ([\d.]+)%\s+(.*)$", text)
                if m:
                    print("| %s | %s | %s |" % (m.group(1), m.group(2), m.group(3).replace("|", "\\|")))
        print()
        if prof_files.get(label):
            print("Scripts by inclusive share: " + ", ".join("%s %s%%" % (name, pct) for _, pct, name in prof_files[label][:12]))
            print()


def loadrow(args):
    """One row of the load tables (tools/render_harness/lua_load.sh, tools/ios/lua_measure.sh): the seconds from the load command (or the click
    on Start) to `level ready` in the shell log, and the engine's [lua-load] line of that load (the first one with more than 300 scripts)."""
    start = ready = None
    try:
        for line in open(args.shell, errors="replace"):
            m = re.match(r"^\[\s*([\d.]+)\] anomaly: script t=[\d.]+ (console start server|click)", line)
            if m and start is None:
                start = float(m.group(1))
            m = re.match(r"^\[\s*([\d.]+)\] anomaly: script: level ready after", line)
            if m and ready is None:
                ready = float(m.group(1))
    except OSError:
        pass
    load = None
    try:
        for line in open(args.engine, errors="replace"):
            if line.startswith("* [lua-load] level"):
                kv = dict(re.findall(r"(\w+)=(\S+)", line))
                if int(kv["files"]) > 300:
                    load = kv
                    break
    except OSError:
        pass
    secs = "%.1f" % (ready - start) if start is not None and ready is not None else "-"
    if load:
        print("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s hits, %s misses, %s stale |" % (
            args.kind, args.config, args.run, secs, load["files"], load["total_ms"], load["read_ms"], load["compile_ms"], load["run_ms"],
            load["hit"], load["miss"], load["stale"]))
    else:
        print("| %s | %s | %s | %s | - | - | - | - | - | no load line |" % (args.kind, args.config, args.run, secs))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--save", required=True, help="the save to load (Mac: h_cordon from run_scene.sh --newgame; iPad: ipad_test)")
    s.add_argument("--mode", default="quality", help="graphics mode of the launch (quality or performance)")
    s.add_argument("--places", default="field,village,bar")
    s.add_argument("--seconds", type=float, default=34)
    s.add_argument("--settle", type=float, default=10)
    s.add_argument("--soak", type=float, default=0, help="seconds to stand in the village first (a warm iPad)")
    s.add_argument("--keys", type=int, default=12, help="taps of Left Shift after a level load (the loading screen waits for a key)")
    s.add_argument("--fps", type=int, default=0)
    s.add_argument("--console", action="append", default=[], metavar="CMD", help="a console command before the level loads")
    s.add_argument("--profile", action="store_true", help="a sampling-profiler run (lua_profile) instead of a timer run")
    s.add_argument("--interval", type=int, default=2, help="profiler sample interval in ms")
    s.add_argument("--top", type=int, default=25)
    r = sub.add_parser("loadrow")
    r.add_argument("--kind", required=True)
    r.add_argument("--config", required=True)
    r.add_argument("--run", required=True)
    r.add_argument("--shell", required=True)
    r.add_argument("--engine", required=True)
    t = sub.add_parser("summarize")
    t.add_argument("--engine", help="engine log (xray_*.log)")
    t.add_argument("--shell", help="shell log (anomaly-shell.log)")
    args = ap.parse_args()
    if args.cmd == "script":
        make_script(args)
    elif args.cmd == "loadrow":
        loadrow(args)
    else:
        summarize(args)


if __name__ == "__main__":
    sys.exit(main())
