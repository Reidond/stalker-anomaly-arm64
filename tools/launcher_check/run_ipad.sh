#!/bin/zsh
# The launcher on the iPad: two runs of the signed app with a virtual DualSense driving the launcher (--launcher-script), so that nobody has
# to hold a pad. Needs the app installed (tools/ios/ipad.sh install), the iPad unlocked, and the iPad granted to this session.
#
#   run 1  the launcher on screen: Mods, the second mod switched off, a reorder, the details, back, with a screenshot of the launcher
#          after each step (the app writes them: Documents/Mods/ipad-*.png); the script then quits the app.
#   run 2  the same navigation, then Play: the engine starts in the same process; its log must show only mod a (mod b is off), then the
#          timeline ends with `mods_clear` (the app deletes what is in Documents/Mods, nothing else) and `quit`.
#
# Safety: only ever adds or overwrites single files and folders below Documents/Mods (never `devicectl device copy to
# --remove-existing-content`), refuses to start when Documents/Mods already holds anything, backs up Library/Application
# Support/Anomaly/appdata first, and deletes nothing itself (devicectl cannot; the app removes its own test files with mods_clear).
#
#   tools/launcher_check/run_ipad.sh [--device <udid|name>] [--out <dir>] [--dry-run]
#
#   --dry-run   makes the files in <out> and stops before touching the iPad
set -euo pipefail

here=${0:A:h}
repo=${here:h:h}
ipad=$repo/tools/ios/ipad.sh
bundle=com.andriishafar.anomaly
device=${ANOMALY_IPAD_UDID:-}
dry=0
out=""
while [[ ${1:-} == --* ]]; do
    case $1 in
        --device) device=$2; shift 2 ;;
        --out) out=$2; shift 2 ;;
        --dry-run) dry=1; shift ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done
dev=(); [[ -n $device ]] && dev=(--device $device)
# a new folder of our own, never an existing one
[[ -n $out ]] || out=$(mktemp -d "${TMPDIR:-/tmp}/launcher-check-ipad-XXXXXX")
[[ -z $(ls -A $out 2>/dev/null) ]] || { echo "$out is not empty: give a new folder" >&2; exit 2; }
mkdir -p $out/files/tree
work=$out/files/tree

# ---- the files: two small mods (a script and a config each), the list, the two launcher scripts and the engine timeline ---------------
make_mod() { # id value
    local d=$work/$1/content/gamedata
    mkdir -p $d/scripts $d/configs
    printf '[test]\nvalue = %s\nwho = mod_%s\n' "$2" "$1" > $d/configs/modtest.ltx
    printf 'function run()\n    log("MODTEST script of mod %s ran")\nend\n' "$1" > $d/scripts/modtest_$1.script
    printf '{"schema":1,"id":"%s","name":"Mod %s","version":"1","file_count":2}\n' "$1" "$1" > $work/$1/mod.json
}
make_mod a from_a
make_mod b from_b
echo '{"schema":1,"mods":[{"id":"a","enabled":true},{"id":"b","enabled":true}]}' > $work/modlist.json
nav() { # the navigation both runs share: Mods, down to mod b, switch it off, Square held + down (reorder), Triangle (details), back, back
    cat <<'NAV'
1.0 padon
2.0 snapshot Mods/ipad-home
2.5 pad down
3.0 pad cross
4.0 snapshot Mods/ipad-mods
4.5 pad down
5.0 pad cross
5.5 snapshot Mods/ipad-b-off
6.0 pad triangle
7.0 snapshot Mods/ipad-details
7.5 pad circle
8.0 pad circle
NAV
}
{ echo "# generated by tools/launcher_check/run_ipad.sh, run 1"; nav; echo "9.0 quit"; } > $work/.launcher1
{ echo "# generated by tools/launcher_check/run_ipad.sh, run 2"; nav; echo "9.5 pad options"; } > $work/.launcher2
# the engine timeline (run 2): what the mods provide, then the app empties Documents/Mods
{
    echo "# generated by tools/launcher_check/run_ipad.sh"
    echo '6 console run_string if modtest_a then modtest_a.run() else log("MODTEST script of mod a missing") end'
    echo '7 console run_string if modtest_b then modtest_b.run() else log("MODTEST script of mod b missing") end'
    echo "9 mods_clear"
    echo "10 quit"
} > $work/.timeline
echo "files are in $out/files"
if [[ $dry -eq 1 ]]; then echo "(dry run: the iPad was not touched)"; exit 0; fi

# ---- what is on the iPad now ------------------------------------------------------------------------------------------
files=$(xcrun devicectl device info files --domain-type appDataContainer --domain-identifier $bundle $dev 2>/dev/null || true)
if print -r -- "$files" | grep -q "Documents/Mods/."; then
    echo "Documents/Mods on the iPad is not empty; not touching it:" >&2
    print -r -- "$files" | grep "Documents/Mods/" | head -10 >&2
    exit 3
fi
echo "== backing up appdata (saves, user.ltx) to $out/appdata-backup"
mkdir -p $out/appdata-backup
$ipad $dev get "Library/Application Support/Anomaly/appdata" $out/appdata-backup >/dev/null 2>&1 || echo "(no appdata to back up yet)"

put_path() { # <local file or folder> <path below the container>: adds or overwrites that one item
    xcrun devicectl device copy to --domain-type appDataContainer --domain-identifier $bundle $dev --source "$1" --destination "$2"
}
final() {
    echo "== what is left in Documents/Mods"
    left=$(xcrun devicectl device info files --domain-type appDataContainer --domain-identifier $bundle $dev 2>/dev/null | grep "Documents/Mods/" || true)
    if [[ -z $left ]]; then
        echo "nothing: Documents/Mods is empty again"
    else
        print -r -- "$left" | head -12
        echo "(run 2 did not reach mods_clear: delete these in the Files app, Documents/Mods)"
    fi
}
trap final EXIT

echo "== copying the test mods to Documents/Mods"
put_path $work/a Documents/Mods/a
put_path $work/b Documents/Mods/b
put_path $work/modlist.json Documents/Mods/modlist.json
put_path $work/.launcher1 Documents/Mods/.launcher1
put_path $work/.launcher2 Documents/Mods/.launcher2
put_path $work/.timeline Documents/Mods/.timeline

run_game() { # <label> <args...>
    echo "== $1"
    shift
    set +e
    $ipad $dev run "$@" 2>&1 | tail -3
    set -e
    sleep 3
}

run_game "run 1: the launcher driven by the virtual pad, screenshots, then quit" --launcher-script Mods/.launcher1
mkdir -p $out/shots
for name in ipad-home ipad-mods ipad-b-off ipad-details; do
    $ipad $dev get Documents/Mods/$name.png $out/shots/$name.png >/dev/null 2>&1 || echo "(no $name.png)"
done
echo "shots: $out/shots"

run_game "run 2: the same, then Play: the engine must see only mod a" --launcher-script Mods/.launcher2 --script Mods/.timeline -dbg
$ipad $dev logs $out/logs >/dev/null 2>&1 || true
echo "-- shell log"
grep -a "launcher\|mods:\|mod [0-9]/\|Play pressed\|engine up" $out/logs/anomaly-shell.log | cut -c1-240 || true
echo "-- engine log"
grep -a -i "\* mod \|MODTEST" $out/logs/engine-logs/xray_*.log | cut -c1-240 || true
echo "logs are in $out"
