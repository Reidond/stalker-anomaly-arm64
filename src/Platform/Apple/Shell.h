struct DisplayInfo
{
    std::string name;
    int native_width = 0;          // physical panel pixels, landscape (width >= height)
    int native_height = 0;
    int drawable_width = 0;        // current window drawable size in pixels (what a Metal layer renders at)
    int drawable_height = 0;
    float window_width = 0;        // current window size in points
    float window_height = 0;
    float scale = 1.0f;            // pixels per point (window pixel density)
    float native_scale = 1.0f;     // the screen's physical scale (UIScreen.nativeScale)
    float refresh_hz = 60.0f;      // what the display is running at right now
    float max_refresh_hz = 60.0f;  // fastest the panel supports (120 on ProMotion iPads)
    bool promotion = false;        // max_refresh_hz > 60
    Insets safe_area_points;       // inset from each window edge, in points
    Insets safe_area_pixels;
};

