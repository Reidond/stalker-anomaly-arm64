// ---------------------------------------------------------------------------------------------
// Game data discovery and validation
// ---------------------------------------------------------------------------------------------

enum class DataState
{
    Ok,         // every required archive is present with the expected size
    NotFound,   // the data root is missing, empty or has no db/ folder
    Incomplete, // some required archives are missing or have the wrong size (interrupted copy, other version)
};

struct DataIssue
{
    std::string path;      // relative to the data root, e.g. "db/textures/textures.db0"
    uint64_t expected = 0; // bytes
    uint64_t actual = 0;   // bytes (0 when missing)
    bool missing = false;
};

struct GameDataStatus
{
    DataState state = DataState::NotFound;
    std::string root;
    std::string summary;           // one line, e.g. "Incomplete: 3 of 68 archives missing"
    std::string help;              // how to fix it (empty when Ok); multi-line, wrapped for ~80 columns
    uint32_t files_expected = 0;
    uint32_t files_ok = 0;
    uint64_t bytes_expected = 0;
    uint64_t bytes_present = 0;    // bytes of the expected files that are present with the right size
    std::vector<DataIssue> issues; // missing / wrong-size archives (capped at 64)
    std::string nested_root;       // data found one folder deeper (a common Files-app mistake); empty if none
    bool has_gamedata_dir = false; // gamedata/ (user addons and overrides) exists
    bool has_original_fsgame = false;
};

// Cheap (about 70 stat calls). Safe to call every time the launcher is shown.
GameDataStatus ValidateGameData(const std::string& root);

