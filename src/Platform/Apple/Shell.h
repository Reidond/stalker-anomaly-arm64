enum class DataRootSource
{
    PlatformDefault, // iPad: Documents/Anomaly; macOS: ~/Documents/Anomaly
    Preference,      // macOS: `defaults write com.andriishafar.anomaly AnomalyDataRoot <path>`
    Environment,     // ANOMALY_DATA_ROOT
    CommandLine,     // --data-root <path>
    InitParams,      // InitParams::data_root_override
};

struct Paths
{
    // Game data (read-only for the game): holds db/, gamedata/ and the other archives. The engine's $fs_root$.
    std::string data_root;
    DataRootSource data_root_source = DataRootSource::PlatformDefault;

    // Library/Application Support/Anomaly: everything the game writes and wants backed up.
    std::string app_support;
    std::string appdata;      // app_support/appdata: saves, screenshots, user.ltx. The engine's $app_data_root$.
    std::string logs;         // appdata/logs: the engine's log files
    std::string saves;        // appdata/savedgames

    // Library/Caches/Anomaly: anything that can be rebuilt; the OS may delete it when storage is low.
    std::string caches;
    std::string shader_cache; // caches/shaders
    std::string lua_cache;    // caches/lua: compiled script bytecode (docs/ios-port/LUA-PERF.md)

    // Where the shell's own files are written. iPad: Documents (visible in the Files app and Finder).
    // macOS: ~/Library/Logs/Anomaly.
    std::string shell_dir;
    std::string shell_log;    // shell_dir/anomaly-shell.log (previous run: anomaly-shell.prev.log)
    std::string crash_log;    // shell_dir/anomaly-crash.log (written when this run crashes)
    std::string crash_log_previous; // shell_dir/anomaly-crash.prev.log: the crash report of the last run that crashed

    // The Monolith gamedata overlay (scripts, configs and shaders the engine build ships next to the game data): the bundle's
    // Resources/overlay folder, or --overlay <dir> / ANOMALY_OVERLAY. Empty when there is none. It is packed into
    // overlay_archive_dir/monolith_overlay.db0 (caches/overlay) at startup and mounted by the generated fsgame.ltx;
    // overlay_archive_dir is cleared when nothing was packed, and nothing is mounted then.
    std::string overlay_source;
    std::string overlay_archive_dir;

    // Generated by WriteFsGameLtx(): app_support/fsgame.ltx. Pass this path to the engine as its fsgame.ltx.
    std::string fsgame_ltx;

    // The mods (docs/ios-port/MOD-MANAGER.md): one folder per mod, <mods_root>/<id>/{mod.json,content/}, and <mods_root>/modlist.json
    // with the order and the enabled flags. iPad: Documents/Mods (visible in the Files app); macOS: Application Support/Anomaly/Mods.
    // ANOMALY_MODS_ROOT=<dir> overrides both; a macOS run with ANOMALY_STATE_ROOT=<dir> uses <dir>/Mods. Created by Init.
    std::string mods_root;
};

