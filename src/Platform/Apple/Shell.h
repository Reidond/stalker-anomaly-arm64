// ---------------------------------------------------------------------------------------------
// Lifecycle, memory pressure, thermal, power
// ---------------------------------------------------------------------------------------------

enum class LifecycleEvent
{
    WillEnterBackground, // app is losing focus: pause now (also fires for Control Center / system alerts)
    DidEnterBackground,  // fully backgrounded: no GPU work is allowed from here until foreground
    WillEnterForeground,
    DidEnterForeground,  // active again: resume
    Terminating,
};
const char* ToString(LifecycleEvent event);

enum class MemoryLevel
{
    Normal,   // pressure over, or back to a comfortable margin
    Warning,  // start trimming: drop caches, lower texture LOD
    Critical, // free everything non-essential immediately or the app will be killed
};
const char* ToString(MemoryLevel level);

enum class MemorySource
{
    SystemPressure, // kernel memory-pressure notification (normal / warn / critical)
    AppWarning,     // UIApplicationDidReceiveMemoryWarning (SDL_EVENT_LOW_MEMORY); reported as Critical
    Budget,         // shell watchdog on os_proc_available_memory (iOS): <768 MB Warning, <384 MB Critical
};
const char* ToString(MemorySource source);

struct MemoryEvent
{
    MemoryLevel level = MemoryLevel::Normal;
    MemoryLevel previous = MemoryLevel::Normal;
    MemorySource source = MemorySource::SystemPressure;
    uint64_t available_bytes = 0; // os_proc_available_memory at the time of the event (0 off iOS)
};

struct Listener
{
    std::function<void(LifecycleEvent)> on_lifecycle;
    std::function<void()> on_pause;   // WillEnterBackground: stop simulating, silence audio, stop GPU submission
    std::function<void()> on_resume;  // DidEnterForeground
    std::function<void(const MemoryEvent&)> on_memory;
    std::function<void(ThermalState state, ThermalState previous)> on_thermal;
    std::function<void(bool low_power)> on_low_power;
};

using ListenerId = uint32_t;
ListenerId AddListener(Listener listener);
void RemoveListener(ListenerId id);

// True between WillEnterBackground and DidEnterForeground.
bool IsPaused();

// Keeps the display from sleeping while the game runs. On by default after Init; the shell drops it
// while paused and restores it on resume.
void SetKeepScreenAwake(bool keep);

struct EventRecord
{
    double time_s = 0;    // seconds since Init
    std::string category; // "lifecycle", "memory", "thermal", "power"
    std::string text;
};
// Most recent events, oldest first. Intended for the launcher / debug overlay.
std::vector<EventRecord> RecentEvents(size_t max_count = 32);

